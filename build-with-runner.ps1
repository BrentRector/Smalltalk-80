<#
.SYNOPSIS
  Build Smalltalk-80 cold start bundle with BlockContextTestRunner

.DESCRIPTION
  Builds the Compiler and generates coldstart_with_runner.json from:
    - Smalltalk-80.st (base system)
    - BlockContextTest_full.st (test methods + 9 diagnostic methods)
    - BlockContextDiagnostics.st (9 diagnostic classes with initialize methods)
    - BlockContextTestRunner.st (runs testAllCombinations automatically)

  Output: Smalltalk80.Interpreter/bin/Debug/net9.0-windows/Data/coldstart_with_runner.json

.PARAMETER Configuration
  Build configuration (Debug or Release). Default: Debug

.EXAMPLE
  .\build-with-runner.ps1
  .\build-with-runner.ps1 -Configuration Release
#>

param(
    [ValidateSet("Debug", "Release")]
    [string]$Configuration = "Debug"
)

$ErrorActionPreference = "Stop"

Write-Host "=== Smalltalk-80 Build with Test Runner ===" -ForegroundColor Cyan
Write-Host

# Build Compiler
Write-Host "Building Compiler..." -ForegroundColor Yellow
dotnet build "Smalltalk80.Compiler/Smalltalk80.Compiler.csproj" -c $Configuration
if ($LASTEXITCODE -ne 0) {
    Write-Error "Compiler build failed"
    exit 1
}

# Verify source files exist
Write-Host
Write-Host "Verifying source files..." -ForegroundColor Yellow

$SourceDir = "Smalltalk-80 Source"
$BaseFile = "$SourceDir/Smalltalk-80.st"
$TestFile = "$SourceDir/Tests/BlockContextTest_full.st"
$DiagnosticsFile = "$SourceDir/Tests/BlockContextDiagnostics.st"
$RunnerFile = "$SourceDir/Tests/BlockContextTestRunner.st"

if (-not (Test-Path $BaseFile)) {
    Write-Error "Base file not found: $BaseFile"
    exit 1
}

if (-not (Test-Path $TestFile)) {
    Write-Error "Test file not found: $TestFile"
    exit 1
}

if (-not (Test-Path $DiagnosticsFile)) {
    Write-Error "Diagnostics file not found: $DiagnosticsFile"
    exit 1
}

if (-not (Test-Path $RunnerFile)) {
    Write-Error "Runner file not found: $RunnerFile"
    exit 1
}

Write-Host "  ✓ All source files found" -ForegroundColor Green

# Compile to coldstart.json (passing multiple source files)
Write-Host
Write-Host "Compiling Smalltalk source to coldstart.json..." -ForegroundColor Yellow
Write-Host "  Sources: $BaseFile" -ForegroundColor Cyan
Write-Host "           $TestFile" -ForegroundColor Cyan
Write-Host "           $DiagnosticsFile" -ForegroundColor Cyan
Write-Host "           $RunnerFile" -ForegroundColor Cyan

$CompilerExe = "Smalltalk80.Compiler/bin/$Configuration/net9.0/Smalltalk80.Compiler.dll"
dotnet $CompilerExe $BaseFile $TestFile $DiagnosticsFile $RunnerFile
if ($LASTEXITCODE -ne 0) {
    Write-Error "Compilation failed"
    exit 1
}

# Copy to Data/coldstart_with_runner.json
$ColdstartSrc = "Smalltalk80.Compiler/bin/$Configuration/net9.0/Data/coldstart.json"
$ColdstartDst = "Smalltalk80.Interpreter/bin/$Configuration/net9.0-windows/Data/coldstart_with_runner.json"

# Ensure Data directory exists
$DataDir = "Smalltalk80.Interpreter/bin/$Configuration/net9.0-windows/Data"
if (-not (Test-Path $DataDir)) {
    New-Item -ItemType Directory -Path $DataDir -Force | Out-Null
}

Write-Host
Write-Host "Copying to Data/coldstart_with_runner.json..." -ForegroundColor Yellow
Copy-Item $ColdstartSrc $ColdstartDst -Force

# Also copy .sources and .changes files (generated by compiler)
$SourcesSrc = "Smalltalk80.Compiler/bin/$Configuration/net9.0/Data/Smalltalk-80.sources"
if (Test-Path $SourcesSrc) {
    Copy-Item $SourcesSrc "$DataDir/Smalltalk-80.sources" -Force
}
$ChangesSrc = "Smalltalk80.Compiler/bin/$Configuration/net9.0/Data/Smalltalk-80.changes"
if (Test-Path $ChangesSrc) {
    Copy-Item $ChangesSrc "$DataDir/Smalltalk-80.changes" -Force
}
Write-Host "  Created: $ColdstartDst" -ForegroundColor Green

Write-Host
Write-Host "=== Build Complete ===" -ForegroundColor Green
Write-Host "Output: $ColdstartDst" -ForegroundColor Green
Write-Host

Write-Host "To run the interpreter with test runner:" -ForegroundColor Cyan
Write-Host "  cd Smalltalk80.Interpreter" -ForegroundColor White
Write-Host "  dotnet run -- --coldstart ../Smalltalk80.Interpreter/bin/$Configuration/net9.0-windows/Data/coldstart_with_runner.json" -ForegroundColor White
Write-Host

Write-Host "Expected output:" -ForegroundColor Yellow
Write-Host "  1. Diagnostic tests (9 individual variable tests):" -ForegroundColor Cyan
Write-Host "     DiagOa initialize... Returned: 11" -ForegroundColor White
Write-Host "     DiagOt1 initialize... Returned: 22" -ForegroundColor White
Write-Host "     DiagOt2 initialize... Returned: 44" -ForegroundColor White
Write-Host "     DiagMa initialize... Returned: 88" -ForegroundColor White
Write-Host "     DiagMt1 initialize... Returned: 166" -ForegroundColor White
Write-Host "     DiagMt2 initialize... Returned: 322" -ForegroundColor White
Write-Host "     DiagIa initialize... Returned: 644" -ForegroundColor White
Write-Host "     DiagIt1 initialize... Returned: 188" -ForegroundColor White
Write-Host "     DiagIt2 initialize... Returned: 266" -ForegroundColor White
Write-Host
Write-Host "  2. Full test suite:" -ForegroundColor Cyan
Write-Host "     BlockContextTestRunner initialize... Returned: 1192" -ForegroundColor White
Write-Host "     (120 tests × 10 points each)" -ForegroundColor DarkGray
Write-Host
