        static void TestIfTrueIfFalse()
        {
            Console.WriteLine("\n3. Testing ifTrue:ifFalse: pattern");
            Console.WriteLine("-" + new string('-', 40));
            
            // Create AST for: (x < 10) ifTrue: ['less'] ifFalse: ['greater']
            var xVar = new VariableNode("x", SourceLocation.Empty);
            var ten = new NumberLiteralNode(10, false, SourceLocation.Empty);
            var lessThan = new BinaryMessageNode("<", ten, SourceLocation.Empty);
            var receiver = new MessageSendNode(xVar, lessThan, SourceLocation.Empty);
            
            // Create true block: ['less']
            var lessStr = new StringLiteralNode("less", SourceLocation.Empty);
            var lessStmt = new ExpressionStatementNode(lessStr, SourceLocation.Empty);
            var trueBlockBody = new StatementListNode(ImmutableArray.Create<StatementNode>(lessStmt), SourceLocation.Empty);
            var trueBlock = new BlockNode(
                ImmutableArray<BlockArgumentNode>.Empty,
                ImmutableArray<TemporaryDeclarationNode>.Empty,
                trueBlockBody,
                SourceLocation.Empty);
            
            // Create false block: ['greater']
            var greaterStr = new StringLiteralNode("greater", SourceLocation.Empty);
            var greaterStmt = new ExpressionStatementNode(greaterStr, SourceLocation.Empty);
            var falseBlockBody = new StatementListNode(ImmutableArray.Create<StatementNode>(greaterStmt), SourceLocation.Empty);
            var falseBlock = new BlockNode(
                ImmutableArray<BlockArgumentNode>.Empty,
                ImmutableArray<TemporaryDeclarationNode>.Empty,
                falseBlockBody,
                SourceLocation.Empty);
            
            // Create ifTrue:ifFalse: message
            var ifTrueIfFalseMsg = new KeywordMessageNode(
                ImmutableArray.Create("ifTrue:", "ifFalse:"),
                ImmutableArray.Create<ExpressionNode>(trueBlock, falseBlock),
                SourceLocation.Empty);
            var ifTrueIfFalseSend = new MessageSendNode(receiver, ifTrueIfFalseMsg, SourceLocation.Empty);
            
            // Compile it
            var context = new CompilationContext();
            var generator = new BytecodeGenerator(context);
            
            // Create a method scope
