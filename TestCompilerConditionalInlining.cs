            Console.WriteLine($"Bytecode ({generator.Bytecode.Count} bytes):");
            DisplayBytecode(generator.Bytecode);
            AnalyzeBytecode(generator.Bytecode);
        }
        
        static void DisplayBytecode(IReadOnlyList<byte> bytecode)
        {
            for (int i = 0; i < bytecode.Count; i++)
            {
                if (i > 0 && i % 16 == 0) Console.WriteLine();
                Console.Write($"{bytecode[i]:X2} ");
            }
            Console.WriteLine();
        }
        
        static void AnalyzeBytecode(IReadOnlyList<byte> bytecode)
        {
            Console.WriteLine("\nBytecode Analysis:");
            int pc = 0;
            while (pc < bytecode.Count)
            {
                byte opcode = bytecode[pc];
                string instruction = "";
                int consumed = 1;
                
                // Detect jump and conditional jump instructions
                if (opcode >= 144 && opcode <= 151)
                {
                    // Short jump: 144-151 jump 1-8 bytes
                    int distance = opcode - 143;
                    instruction = $"[{pc:D3}] Jump {distance} bytes forward";
                }
                else if (opcode == 160)
                {
                    // Medium jump with 1 byte parameter
                    if (pc + 1 < bytecode.Count)
                    {
                        int distance = bytecode[pc + 1] + 1;
                        instruction = $"[{pc:D3}] Jump {distance} bytes forward";
                        consumed = 2;
                    }
                }
                else if (opcode >= 152 && opcode <= 159)
                {
                    // Short conditional jump on false: 152-159
                    int distance = opcode - 151;
                    instruction = $"[{pc:D3}] Pop and Jump-on-False {distance} bytes forward";
                }
                else if (opcode == 168)
                {
                    // Medium conditional jump on false with 1 byte parameter
                    if (pc + 1 < bytecode.Count)
                    {
                        int distance = bytecode[pc + 1] + 1;
                        instruction = $"[{pc:D3}] Pop and Jump-on-False {distance} bytes forward";
                        consumed = 2;
                    }
                }
                else if (opcode >= 16 && opcode <= 31)
                {
                    instruction = $"[{pc:D3}] Push Temporary Variable [{opcode - 16}]";
                }
                else if (opcode >= 32 && opcode <= 63)
                {
                    instruction = $"[{pc:D3}] Push Literal Constant [{opcode - 32}]";
                }
                else if (opcode >= 104 && opcode <= 111)
                {
                    instruction = $"[{pc:D3}] Pop and Store into Temporary Variable [{opcode - 104}]";
                }
                else if (opcode == 176)
                {
                    instruction = $"[{pc:D3}] Send + (arithmetic)";
                }
                else if (opcode == 177)
                {
                    instruction = $"[{pc:D3}] Send - (arithmetic)";
                }
                else if (opcode == 178)
                {
                    instruction = $"[{pc:D3}] Send < (comparison)";
                }
                else if (opcode == 179)
                {
                    instruction = $"[{pc:D3}] Send > (comparison)";
                }
                
                if (!string.IsNullOrEmpty(instruction))
                {
                    Console.WriteLine(instruction);
                }
                
                pc += consumed;
            }
        }
    }
