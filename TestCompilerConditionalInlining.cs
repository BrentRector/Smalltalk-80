using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using Smalltalk80.Compiler.AST;
using Smalltalk80.Compiler.Compilation;
using Smalltalk80.Compiler.Compilation.Models;

namespace TestCompilerConditionalInlining
{
    /// <summary>
    /// Test program to verify conditional inlining in the Smalltalk80.Compiler.
    /// </summary>
    class Program
    {
        static void Main(string[] args)
        {
            Console.WriteLine("Testing Conditional Inlining in Smalltalk80.Compiler\n");
            Console.WriteLine("=" + new string('=', 60));
            
            TestIfTrue();
            TestIfFalse();
            TestIfTrueIfFalse();
            
            Console.WriteLine("\nAll tests completed!");
        }
        
        static void TestIfTrue()
        {
            Console.WriteLine("\n1. Testing ifTrue: pattern");
            Console.WriteLine("-" + new string('-', 40));
            
            // Create AST for: (x < 10) ifTrue: [x := x + 1]
            var xVar = new VariableNode("x", SourceLocation.Empty);
            var ten = new NumberLiteralNode(10, false, SourceLocation.Empty);
            var lessThan = new BinaryMessageNode("<", ten, SourceLocation.Empty);
            var receiver = new MessageSendNode(xVar, lessThan, SourceLocation.Empty);
            
            // Create block: [x := x + 1]
            var xVar2 = new VariableNode("x", SourceLocation.Empty);
            var xVar3 = new VariableNode("x", SourceLocation.Empty);
            var one = new NumberLiteralNode(1, false, SourceLocation.Empty);
            var plus = new BinaryMessageNode("+", one, SourceLocation.Empty);
            var addition = new MessageSendNode(xVar3, plus, SourceLocation.Empty);
            var assignment = new AssignmentNode("x", addition, SourceLocation.Empty);
            var assignmentStmt = new ExpressionStatementNode(assignment, SourceLocation.Empty);
            var blockBody = new StatementListNode(ImmutableArray.Create<StatementNode>(assignmentStmt), SourceLocation.Empty);
            var block = new BlockNode(
                ImmutableArray<BlockArgumentNode>.Empty,
                ImmutableArray<TemporaryDeclarationNode>.Empty,
                blockBody,
                SourceLocation.Empty);
            
            // Create ifTrue: message
            var ifTrueMsg = new KeywordMessageNode(
                ImmutableArray.Create("ifTrue:"),
                ImmutableArray.Create<ExpressionNode>(block),
                SourceLocation.Empty);
            var ifTrueSend = new MessageSendNode(receiver, ifTrueMsg, SourceLocation.Empty);
            
            // Compile it
            var context = new CompilationContext();
            var generator = new BytecodeGenerator(context);
            
            // Create a method scope
            var methodScope = new CompilationScope
            {
                Type = ScopeType.Method,
                Arguments = [],
                Temporaries = ["x"],
                InstanceVariables = [],
                ClassVariables = []
            };
            context.PushScope(methodScope);
            
            // Visit the ifTrue: send
            ifTrueSend.Accept(generator);
            
            // Display results
            Console.WriteLine("Generated bytecode for: (x < 10) ifTrue: [x := x + 1]");
            Console.WriteLine($"Bytecode ({generator.Bytecode.Count} bytes):");
            DisplayBytecode(generator.Bytecode);
            AnalyzeBytecode(generator.Bytecode);
        }
        
