namespace Smalltalk80.Interpreter.ColdStart;

using Smalltalk80.Interpreter.Core.Objects;
using Smalltalk80.Interpreter.Core.Values;
using Smalltalk80.Interpreter.Generated;
using Smalltalk80.Interpreter.Memory;

/// <summary>
/// Builds the Symbol USTable (Unique String Table) during cold start.
/// Per Blue Book: All Symbol instances are stored in a hash table for uniqueness.
///
/// COLD START KNOWLEDGE (isolated to this file):
/// - Symbol class has classVariable 'USTable' which is the symbol hash table
/// - USTable is an Array of buckets (each bucket is an Array of Symbol instances)
/// - Symbol lookup uses string hashing to find bucket, then linear search
/// - Symbols are unique (only one instance per string)
/// </summary>
public static class SymbolTableBuilder
{
    // Cache Symbol class ref to avoid circular dependency during GetUSTable
    private static SObjectRef? _symbolClassCache = null;

    /// <summary>
    /// Creates the USTable and installs it in Symbol class's classPool in one atomic operation.
    /// This ensures bucket pre-sizing accounts for the "USTable" symbol itself.
    /// </summary>
    public static void CreateAndInstallUSTable()
    {
        // First, pre-create the "USTable" symbol (without adding to any table yet)
        // so we can include it in bucket size calculations
        var usTableSymbolOop = ObjectMemoryNew.InternSymbolBootstrap("USTable");

        if (Program.RuntimeOptions?.EnableColdStartLogging ?? false)
        {
            Console.WriteLine("[SymbolTableBuilder] About to pre-intern kernel selectors...");
        }

        // Pre-intern all method selector symbols that will be created during cold start
        // This prevents bucket growth (and garbage creation) when methods are installed later
        PreInternKernelSelectors();

        if (Program.RuntimeOptions?.EnableColdStartLogging ?? false)
        {
            Console.WriteLine("[SymbolTableBuilder] About to create USTable with pre-sized buckets...");
        }

        // Now create USTable with correct bucket sizes (including USTable symbol and all kernel selectors)
        var usTable = CreateUSTableInternal();

        // Install USTable in Symbol class classPool (reuses the symbol we just created)
        InstallUSTable(usTable);
    }

    /// <summary>
    /// Pre-interns all symbols that will be needed during cold start.
    /// This ensures USTable buckets are pre-sized correctly to avoid growth and garbage creation.
    /// The symbol list is automatically generated by the Smalltalk80.Compiler from the AST.
    /// Generated file: ColdStartLiterals.cs
    /// </summary>
    private static void PreInternKernelSelectors()
    {
        // Use the auto-generated symbol list from the compiler
        foreach (var symbol in ColdStartLiterals.Symbols)
        {
            ObjectMemoryNew.InternSymbolBootstrap(symbol);
        }

        // CRITICAL: Pre-intern symbols used after USTable creation to avoid bucket growth
        ObjectMemoryNew.InternSymbolBootstrap("SymbolTable");  // Used in Phase2_4_CreateUSTable

        if (Program.RuntimeOptions?.EnableColdStartLogging ?? false)
        {
            int totalBootstrapSymbols = ObjectMemoryNew.GetBootstrapSymbolTable().Count;
            Console.WriteLine($"[SymbolTableBuilder] Pre-interned {ColdStartLiterals.Symbols.Length} symbols from ColdStartLiterals");
            Console.WriteLine($"[SymbolTableBuilder] Total bootstrap symbols: {totalBootstrapSymbols}");
        }
    }

    /// <summary>
    /// Creates the USTable (Unique String Table) for Symbol class with pre-sized buckets.
    /// Internal method - use CreateAndInstallUSTable() instead.
    /// </summary>
    private static SObjectRef CreateUSTableInternal()
    {
        var symbolClassRef = SystemDictionary.LookupClassRef("Symbol");
        if (!symbolClassRef.HasValue || symbolClassRef.Value.IsNil)
            throw new InvalidOperationException("Symbol class must be created before USTable");

        var arrayClassRef = SystemDictionary.LookupClassRef("Array");
        if (!arrayClassRef.HasValue || arrayClassRef.Value.IsNil)
            throw new InvalidOperationException("Array class must be created before USTable");

        // Create hash table with reasonable initial size (must be power of 2 for efficient modulo)
        const int initialBucketCount = 256;

        // Compute bucket assignments using the same algorithm as migration
        var buckets = ObjectMemoryNew.ComputeSymbolBuckets(initialBucketCount);

        nint tableOop = ObjectMemoryNew.AllocateObject(
            arrayClassRef.Value,
            ObjectFormat.PointerIndexed,
            instanceVarCount: 0,
            indexedSize: initialBucketCount
        );
        var usTable = SObjectRef.FromObjectPointer(tableOop);

        // Initialize each bucket to array with exact size needed
        // This avoids creating garbage when symbols are added during migration
        for (int i = 0; i < initialBucketCount; i++)
        {
            int bucketSize = buckets.ContainsKey(i) ? buckets[i].Count : 0;

            var bucketOop = ObjectMemoryNew.AllocateObject(
                arrayClassRef.Value,
                ObjectFormat.PointerIndexed,
                instanceVarCount: 0,
                indexedSize: bucketSize
            );

            usTable.SetIndexedPointer(i, SObjectRef.FromObjectPointer(bucketOop));
        }

        if (Program.RuntimeOptions?.EnableColdStartLogging ?? false)
        {
            int totalSymbols = buckets.Values.Sum(list => list.Count);
            Console.WriteLine($"[SymbolTableBuilder] Created USTable with {initialBucketCount} buckets (pre-sized for {totalSymbols} symbols)");
        }

        return usTable;
    }

    /// <summary>
    /// Installs the USTable as a class variable in the Symbol class's classPool.
    /// Symbol class inherits from String -> ByteArray -> SequenceableCollection -> Collection -> Object -> ProtoObject.
    /// Class structure: Symbol class has classPool (Dictionary) which should contain #USTable -> the hash table.
    /// </summary>
    public static void InstallUSTable(SObjectRef usTable)
    {
        var symbolClassRef = SystemDictionary.LookupClassRef("Symbol");
        if (!symbolClassRef.HasValue || symbolClassRef.Value.IsNil)
            throw new InvalidOperationException("Symbol class must exist");

        // Cache the Symbol class to avoid lookups during GetUSTable
        _symbolClassCache = symbolClassRef.Value;

        // Get the Symbol class object
        var symbolClassOop = symbolClassRef.Value.AsObjectPointer();

        // Symbol class inherits from Class, which has:
        // Slot 0-5: inherited from Behavior/ClassDescription (superclass, methodDict, format, instanceVariables, organization, name)
        // Slot 6: name (actually at index 6 in ClassLayout)
        // Slot 7: classPool (Dictionary) - per BlueBook ClassLayout.ClassPool = 7
        // Slot 8: sharedPools

        // Get or create the classPool Dictionary
        var classPoolRef = ObjectMemoryNew.GetInstanceVariable(symbolClassOop, Core.BlueBook.ClassLayout.ClassPool);

        if (classPoolRef.IsNil)
        {
            // Create new Dictionary for classPool
            var dictionaryClassRef = SystemDictionary.DictionaryClassRef;
            if (dictionaryClassRef.IsNil)
                throw new InvalidOperationException("Dictionary class must exist");

            var newClassPoolOop = ObjectMemoryNew.AllocateObject(
                dictionaryClassRef,
                ObjectFormat.PointerIndexed,
                instanceVarCount: 1, // tally
                indexedSize: 16 // initial capacity for associations
            );
            classPoolRef = SObjectRef.FromObjectPointer(newClassPoolOop);

            // Initialize tally to 0
            classPoolRef.SetInstanceVariable(0, SObjectRef.FromSmallInteger(0));

            // Set classPool in Symbol class
            ObjectMemoryNew.SetInstanceVariable(symbolClassOop, Core.BlueBook.ClassLayout.ClassPool, classPoolRef);
        }

        // Add Association #USTable -> usTable to classPool
        var associationClassRef = SystemDictionary.LookupClassRef("Association");
        if (!associationClassRef.HasValue || associationClassRef.Value.IsNil)
            throw new InvalidOperationException("Association class must exist");

        // Get #USTable symbol (already created by CreateAndInstallUSTable)
        var usTableSymbol = ObjectMemoryNew.InternSymbolBootstrap("USTable");

        // Create Association: key=#USTable, value=usTable
        var associationOop = ObjectMemoryNew.AllocateObject(
            associationClassRef.Value,
            ObjectFormat.FixedPointer,
            instanceVarCount: 2, // key, value
            indexedSize: 0
        );
        var association = SObjectRef.FromObjectPointer(associationOop);
        association.SetInstanceVariable(0, usTableSymbol); // key
        association.SetInstanceVariable(1, usTable);       // value

        // Add association to classPool Dictionary
        // Simple implementation: find nil slot and add
        var indexedSize = ObjectMemoryNew.GetIndexedSize(classPoolRef.AsObjectPointer());

        for (int i = 0; i < indexedSize; i++)
        {
            var slot = classPoolRef.GetIndexedPointer(i);
            if (slot.IsNil)
            {
                classPoolRef.SetIndexedPointer(i, association);

                // Increment tally
                var tally = classPoolRef.GetInstanceVariable(0);
                if (tally.IsSmallInteger)
                {
                    classPoolRef.SetInstanceVariable(0, SObjectRef.FromSmallInteger(tally.AsSmallInteger() + 1));
                }

                break;
            }
        }

        if (Program.RuntimeOptions?.EnableColdStartLogging ?? false)
        {
            Console.WriteLine("[SymbolTableBuilder] USTable installed in Symbol class classPool");
        }
    }

    /// <summary>
    /// Gets the USTable from Symbol class's classPool.
    /// NOTE: This method MUST NOT call InternSymbol to avoid infinite recursion.
    /// </summary>
    public static SObjectRef? GetUSTable()
    {
        // Use cached Symbol class to avoid circular dependency
        if (!_symbolClassCache.HasValue || _symbolClassCache.Value.IsNil)
            return null;

        var symbolClassOop = _symbolClassCache.Value.AsObjectPointer();
        var classPoolRef = ObjectMemoryNew.GetInstanceVariable(symbolClassOop, Core.BlueBook.ClassLayout.ClassPool);

        if (classPoolRef.IsNil)
            return null;

        // Search classPool for #USTable association
        // IMPORTANT: Compare by string value, NOT by interning (which would cause infinite recursion)
        var indexedSize = ObjectMemoryNew.GetIndexedSize(classPoolRef.AsObjectPointer());

        for (int i = 0; i < indexedSize; i++)
        {
            var association = classPoolRef.GetIndexedPointer(i);
            if (association.IsNil)
                continue;

            var key = association.GetInstanceVariable(0);
            if (key.IsHeapObject)
            {
                // Compare symbol string value
                try
                {
                    var keyString = ObjectMemoryNew.SymbolToString(key);
                    if (keyString == "USTable")
                    {
                        return association.GetInstanceVariable(1); // value
                    }
                }
                catch
                {
                    // Not a symbol, skip
                    continue;
                }
            }
        }

        return null;
    }
}
