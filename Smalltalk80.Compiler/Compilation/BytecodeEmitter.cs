using System.Collections.Generic;

namespace Smalltalk80.Compiler.Compilation;

/// <summary>
/// Handles bytecode emission and literal frame management.
/// </summary>
public sealed class BytecodeEmitter
{
    private readonly List<byte> _bytecode = new();
    private readonly List<object> _literals = new();
    private readonly Dictionary<object, int> _literalMap = new();
    private readonly Stack<int> _stackDepth = new();
    private int _currentStackDepth;
    private int _maxStackDepth;

    // Special selectors for optimization
    private static readonly Dictionary<string, int> SpecialArithmeticSelectors = new()
    {
        ["+"] = 176, ["-"] = 177, ["<"] = 178, [">"] = 179,
        ["<="] = 180, [">="] = 181, ["="] = 182, ["~="] = 183,
        ["*"] = 184, ["/"] = 185, ["\\\\"] = 186, ["@"] = 187,
        ["bitShift:"] = 188, ["//"] = 189, ["bitAnd:"] = 190, ["bitOr:"] = 191
    };

    private static readonly Dictionary<string, int> SpecialSelectors = new()
    {
        ["at:"] = 192, ["at:put:"] = 193, ["size"] = 194, ["next"] = 195,
        ["nextPut:"] = 196, ["atEnd"] = 197, ["=="] = 198, ["class"] = 199,
        ["blockCopy:"] = 200, ["value"] = 201, ["value:"] = 202, ["do:"] = 203,
        ["new"] = 204, ["new:"] = 205, ["x"] = 206, ["y"] = 207
    };

    /// <summary>
    /// Gets the current position in the bytecode stream.
    /// </summary>
    public int CurrentPosition => _bytecode.Count;

    /// <summary>
    /// Gets the maximum stack depth reached.
    /// </summary>
    public int MaxStackDepth => _maxStackDepth;

    /// <summary>
    /// Clears the emitter state.
    /// </summary>
    public void Clear()
    {
        _bytecode.Clear();
        _literals.Clear();
        _literalMap.Clear();
        _stackDepth.Clear();
        _currentStackDepth = 0;
        _maxStackDepth = 0;
    }

    /// <summary>
    /// Gets the generated bytecode.
    /// </summary>
    public byte[] GetBytecode() => _bytecode.ToArray();

    /// <summary>
    /// Gets the literal frame.
    /// </summary>
    public object[] GetLiterals() => _literals.ToArray();

    /// <summary>
    /// Adds a literal to the frame and returns its index.
    /// </summary>
    public int AddLiteral(object literal)
    {
        var key = GetLiteralKey(literal);
        if (_literalMap.TryGetValue(key, out int index))
            return index;

        index = _literals.Count;
        _literals.Add(literal);
        _literalMap[key] = index;
        return index;
    }

    private object GetLiteralKey(object literal)
    {
        if (literal is Symbol sym)
            return $"symbol:{sym.Name}";
        if (literal is Association assoc)
            return $"assoc:{assoc.Key}";
        if (literal is object[] array)
            return $"array:{array.GetHashCode()}";
        return literal;
    }

    // Stack management
    private void Push(int count = 1)
    {
        _currentStackDepth += count;
        if (_currentStackDepth > _maxStackDepth)
            _maxStackDepth = _currentStackDepth;
    }

    private void Pop(int count = 1)
    {
        _currentStackDepth -= count;
        if (_currentStackDepth < 0)
            _currentStackDepth = 0;
    }

    // Basic emission
    private void Emit(byte bytecode)
    {
        _bytecode.Add(bytecode);
    }

    private void Emit(byte bytecode1, byte bytecode2)
    {
        _bytecode.Add(bytecode1);
        _bytecode.Add(bytecode2);
    }

    private void Emit(byte bytecode1, byte bytecode2, byte bytecode3)
    {
        _bytecode.Add(bytecode1);
        _bytecode.Add(bytecode2);
        _bytecode.Add(bytecode3);
    }

    // Push instructions
    public void PushReceiverVariable(int index)
    {
        Push();
        if (index <= 15)
            Emit((byte)(0 + index)); // 0-15
        else
        {
            Emit(128); // Extended push
            Emit((byte)(0x00 | (index & 0x3F))); // Receiver variable type
        }
    }

    public void PushTemporary(int index)
    {
        Push();
        if (index <= 15)
            Emit((byte)(16 + index)); // 16-31
        else
        {
            Emit(128); // Extended push
            Emit((byte)(0x40 | (index & 0x3F))); // Temporary type
        }
    }

    public void PushLiteralConstant(object literal)
    {
        Push();
        int index = AddLiteral(literal);
        
        if (index <= 31)
            Emit((byte)(32 + index)); // 32-63
        else
        {
            Emit(128); // Extended push
            Emit((byte)(0x80 | (index & 0x3F))); // Literal constant type
        }
    }

    public void PushLiteralVariable(string name)
    {
        Push();
        var association = new Association(name, null);
        int index = AddLiteral(association);
        
        if (index <= 31)
            Emit((byte)(64 + index)); // 64-95
        else
        {
            Emit(128); // Extended push
            Emit((byte)(0xC0 | (index & 0x3F))); // Literal variable type
        }
    }

    public void PushSelf()
    {
        Push();
        Emit(112);
    }

    public void PushTrue()
    {
        Push();
        Emit(113);
    }

    public void PushFalse()
    {
        Push();
        Emit(114);
    }

    public void PushNil()
    {
        Push();
        Emit(115);
    }

    public void PushInteger(int value)
    {
        Push();
        switch (value)
        {
            case -1: Emit(116); break;
            case 0: Emit(117); break;
            case 1: Emit(118); break;
            case 2: Emit(119); break;
            default: PushLiteralConstant(value); break;
        }
    }

    // Store instructions
    public void StoreReceiverVariable(int index)
    {
        if (index <= 7)
        {
            Pop();
            Push();
            Emit((byte)(96 + index)); // 96-103 (pop and store)
            Push(); // Value remains on stack
            Dup(); // Duplicate for store semantics
            Pop();
        }
        else
        {
            Emit(129); // Extended store
            Emit((byte)(0x00 | (index & 0x3F)));
        }
    }

    public void PopAndStoreReceiverVariable(int index)
    {
        Pop();
        if (index <= 7)
            Emit((byte)(96 + index)); // 96-103
        else
        {
            Emit(130); // Extended pop and store
            Emit((byte)(0x00 | (index & 0x3F)));
        }
    }

    public void StoreTemporary(int index)
    {
        if (index <= 7)
        {
            Pop();
            Push();
            Emit((byte)(104 + index)); // 104-111 (pop and store)
            Push(); // Value remains on stack
            Dup(); // Duplicate for store semantics
            Pop();
        }
        else
        {
            Emit(129); // Extended store
            Emit((byte)(0x40 | (index & 0x3F)));
        }
    }

    public void PopAndStoreTemporary(int index)
    {
        Pop();
        if (index <= 7)
            Emit((byte)(104 + index)); // 104-111
        else
        {
            Emit(130); // Extended pop and store
            Emit((byte)(0x40 | (index & 0x3F)));
        }
    }

    public void StoreLiteralVariable(string name)
    {
        var association = new Association(name, null);
        int index = AddLiteral(association);
        Emit(129); // Extended store
        Emit((byte)(0xC0 | (index & 0x3F)));
    }

    public void PopAndStoreLiteralVariable(string name)
    {
        Pop();
        var association = new Association(name, null);
        int index = AddLiteral(association);
        Emit(130); // Extended pop and store
        Emit((byte)(0xC0 | (index & 0x3F)));
    }

    // Stack operations
    public void Pop()
    {
        Pop(1);
        Emit(135);
    }

    public void Dup()
    {
        Push();
        Emit(136);
    }

    // Return instructions
    public void ReturnSelf()
    {
        Emit(120);
    }

    public void ReturnTrue()
    {
        Emit(121);
    }

    public void ReturnFalse()
    {
        Emit(122);
    }

    public void ReturnNil()
    {
        Emit(123);
    }

    public void ReturnTop()
    {
        Pop();
        Emit(124);
    }

    public void ReturnTopFromBlock()
    {
        Pop();
        Emit(125);
    }

    public bool LastInstructionIsReturn()
    {
        if (_bytecode.Count == 0) return false;
        byte last = _bytecode[_bytecode.Count - 1];
        return last >= 120 && last <= 125;
    }

    // Message send instructions
    public void EmitSend(string selector, int argCount)
    {
        Pop(argCount + 1); // Pop receiver and arguments
        Push(); // Push result

        // Check for special arithmetic selectors
        if (argCount == 1 && SpecialArithmeticSelectors.TryGetValue(selector, out int arithmeticBytecode))
        {
            Emit((byte)arithmeticBytecode);
            return;
        }

        // Check for special selectors
        if (SpecialSelectors.TryGetValue(selector, out int specialBytecode))
        {
            Emit((byte)specialBytecode);
            return;
        }

        // Regular send
        int selectorIndex = AddLiteral(new Symbol(selector));

        if (argCount == 0 && selectorIndex <= 15)
            Emit((byte)(208 + selectorIndex)); // 208-223
        else if (argCount == 1 && selectorIndex <= 15)
            Emit((byte)(224 + selectorIndex)); // 224-239
        else if (argCount == 2 && selectorIndex <= 15)
            Emit((byte)(240 + selectorIndex)); // 240-255
        else if (argCount <= 7 && selectorIndex <= 31)
        {
            Emit(131); // Single extended send
            Emit((byte)((argCount << 5) | selectorIndex));
        }
        else
        {
            Emit(132); // Double extended send
            Emit((byte)selectorIndex);
            Emit((byte)argCount);
        }
    }

    public void EmitSuperSend(string selector, int argCount)
    {
        Pop(argCount + 1); // Pop receiver and arguments
        Push(); // Push result

        int selectorIndex = AddLiteral(new Symbol(selector));

        if (argCount <= 7 && selectorIndex <= 31)
        {
            Emit(133); // Single extended super send
            Emit((byte)((argCount << 5) | selectorIndex));
        }
        else
        {
            Emit(134); // Double extended super send
            Emit((byte)selectorIndex);
            Emit((byte)argCount);
        }
    }

    // Block operations
    public void EmitBlockCopy(int argCount)
    {
        Push(); // Block copy pushes block
        Emit(200); // blockCopy: bytecode
        Emit((byte)argCount);
    }

    // Jump operations
    public void EmitJump(int distance)
    {
        if (distance <= 8)
        {
            Emit((byte)(143 + distance)); // 144-151
        }
        else
        {
            int offset = (distance - 4) / 256;
            int remainder = (distance - 4) % 256;
            Emit((byte)(160 + offset)); // 160-167
            Emit((byte)remainder);
        }
    }

    public void EmitConditionalJump(int distance, bool onTrue)
    {
        Pop(); // Pop condition
        
        if (distance <= 8 && !onTrue)
        {
            Emit((byte)(151 + distance)); // 152-159 (jump on false)
        }
        else
        {
            int offset = distance / 256;
            int remainder = distance % 256;
            if (onTrue)
                Emit((byte)(168 + offset)); // 168-171 (long jump on true)
            else
                Emit((byte)(172 + offset)); // 172-175 (long jump on false)
            Emit((byte)remainder);
        }
    }

    public void PatchJump(int position, int distance)
    {
        if (_bytecode[position] >= 144 && _bytecode[position] <= 151)
        {
            _bytecode[position] = (byte)(143 + distance);
        }
        else if (_bytecode[position] >= 160 && _bytecode[position] <= 167)
        {
            int offset = (distance - 4) / 256;
            int remainder = (distance - 4) % 256;
            _bytecode[position] = (byte)(160 + offset);
            _bytecode[position + 1] = (byte)remainder;
        }
    }

    public void PatchBlockSize(int blockCopyPos, int blockSize)
    {
        // After blockCopy:, we need to jump over the block
        // The jump instruction is at blockCopyPos + 2 (after blockCopy: and argCount)
        int jumpPos = blockCopyPos + 2;
        PatchJump(jumpPos, blockSize);
    }
}

/// <summary>
/// Represents a Smalltalk symbol.
/// </summary>
public sealed class Symbol
{
    /// <summary>
    /// Gets the symbol name.
    /// </summary>
    public string Name { get; }

    /// <summary>
    /// Initializes a new instance of the Symbol class.
    /// </summary>
    /// <param name="name">The symbol name.</param>
    public Symbol(string name)
    {
        Name = name ?? string.Empty;
    }

    /// <inheritdoc/>
    public override string ToString() => $"#{Name}";

    /// <inheritdoc/>
    public override bool Equals(object? obj) => obj is Symbol sym && Name == sym.Name;

    /// <inheritdoc/>
    public override int GetHashCode() => Name.GetHashCode();
}

/// <summary>
/// Represents a Smalltalk association (key-value pair).
/// </summary>
public sealed class Association
{
    /// <summary>
    /// Gets the association key.
    /// </summary>
    public string Key { get; }

    /// <summary>
    /// Gets the association value.
    /// </summary>
    public object? Value { get; }

    /// <summary>
    /// Initializes a new instance of the Association class.
    /// </summary>
    /// <param name="key">The key.</param>
    /// <param name="value">The value.</param>
    public Association(string key, object? value)
    {
        Key = key ?? string.Empty;
        Value = value;
    }

    /// <inheritdoc/>
    public override string ToString() => $"Association(key: #{Key}, value: {Value ?? "null"})";
}