namespace Smalltalk80.Compiler.Compilation;

using System.Text.Json;
using Smalltalk80.Compiler.AST;
using Smalltalk80.Compiler.AST.Processors;
using Smalltalk80.Compiler.Compilation.Models;

/// <summary>
/// Generates Smalltalk-80 bytecode from AST nodes using modern C# patterns.
/// Implements both the visitor pattern for AST traversal and IAstProcessor for standalone compilation.
/// Can be used directly for bytecode generation or as a processor for JSON output.
/// </summary>
public sealed class BytecodeGenerator : IAstVisitor<object?>, IAstProcessor
{
    private readonly List<byte> _bytecode = [];
    private readonly CompilationContext _context;
    private readonly Stack<int> _jumpFixups = new();
    private readonly Stack<BlockContext> _blockContexts = new();
    private CompilationScope? _currentScope;
    private int _currentStackDepth;
    private int _maxStackDepth;
    
    // Track method compilation state for JSON generation
    private ProcessorContext? _processorContext;
    private int _methodArgCount;
    private int _methodTempCount;
    private int? _primitiveNumber;
    
    /// <summary>
    /// Initializes a new instance of the BytecodeGenerator class.
    /// </summary>
    /// <param name="context">The compilation context containing class and variable information.</param>
    public BytecodeGenerator(CompilationContext context)
    {
        _context = context ?? throw new ArgumentNullException(nameof(context));
    }
    
    /// <summary>
    /// Initializes a new instance of the BytecodeGenerator class with a default context.
    /// Used when implementing IAstProcessor for standalone compilation.
    /// </summary>
    public BytecodeGenerator() : this(new CompilationContext())
    {
    }
    
    /// <summary>
    /// Gets the generated bytecode.
    /// </summary>
    public IReadOnlyList<byte> Bytecode => _bytecode;
    
    /// <summary>
    /// Gets the maximum stack depth reached during compilation.
    /// </summary>
    public int MaxStackDepth => _maxStackDepth;
    
    /// <summary>
    /// Gets the current compilation scope.
    /// </summary>
    public CompilationScope? CurrentScope => _currentScope ?? _context.CurrentScope;
    
    /// <summary>
    /// Gets the literals from the last compiled method.
    /// </summary>
    public IReadOnlyList<object> LastMethodLiterals { get; private set; } = [];
    
    #region IAstProcessor Implementation
    
    /// <inheritdoc/>
    public string Name => "Bytecode Generator";
    
    /// <inheritdoc/>
    public ProcessorResult Process(AstNode node, ProcessorContext context)
    {
        _processorContext = context;
        _context.Reset();
        
        // Reset method state
        _methodArgCount = 0;
        _methodTempCount = 0;
        _primitiveNumber = null;
        _bytecode.Clear();
        LastMethodLiterals = [];
        _maxStackDepth = 0;
        _currentStackDepth = 0;
        
        try
        {
            // Process the AST based on its type
            if (node is MethodDefinitionNode methodNode)
            {
                CompileMethod(methodNode);
            }
            else if (node is ProgramNode programNode)
            {
                CompileProgram(programNode);
            }
            else
            {
                // For other nodes, compile as an expression
                CompileExpression(node);
            }
            
            // Generate JSON output
            var json = GenerateJsonOutput();
            return new BytecodeResult(json);
        }
        catch (Exception ex)
        {
            return BytecodeResult.Failure($"Compilation failed: {ex.Message}");
        }
    }
    
    /// <summary>
    /// Compiles a method definition for JSON output.
    /// </summary>
    private void CompileMethod(MethodDefinitionNode methodNode)
    {
        // Store method metadata
        _methodArgCount = methodNode.Arguments.Length;
        _methodTempCount = methodNode.Temporaries.Length;
        _primitiveNumber = methodNode.Primitive?.PrimitiveNumber;
        
        // Set up default class context if needed
        _context.SetClassContext("Object", false);
        
        // Compile the method using the visitor
        methodNode.Accept(this);
    }
    
    /// <summary>
    /// Compiles a program (multiple methods/classes) for JSON output.
    /// </summary>
    private void CompileProgram(ProgramNode programNode)
    {
        // For programs, compile the first method found
        foreach (var element in programNode.Elements)
        {
            if (element is ClassDefinitionNode classNode)
            {
                // Set up class context
                var classDef = new ClassDefinition(
                    classNode.ClassName,
                    classNode.SuperclassName ?? "Object")
                {
                    InstanceVariables = classNode.InstanceVariables.ToList(),
                    ClassVariables = classNode.ClassVariables.ToList(),
                    PoolDictionaries = [],
                    Category = "Unclassified",
                    Comment = "",
                    MethodReferences = []
                };
                _context.AddOrUpdateClass(classDef);
                _context.SetClassContext(classNode.ClassName, false);
                
                // Compile the first method
                if (classNode.Methods.Length > 0)
                {
                    CompileMethod(classNode.Methods[0]);
                    return;
                }
            }
            else if (element is MethodDefinitionNode methodNode)
            {
                CompileMethod(methodNode);
                return;
            }
        }
        
        // If no methods found, compile as an expression
        programNode.Accept(this);
    }
    
    /// <summary>
    /// Compiles a single expression for JSON output.
    /// </summary>
    private void CompileExpression(AstNode node)
    {
        // Create a simple scope for the expression
        var expressionScope = new CompilationScope
        {
            Type = ScopeType.Expression,
            Arguments = [],
            Temporaries = [],
            InstanceVariables = [],
            ClassVariables = []
        };
        
        _context.PushScope(expressionScope);
        
        try
        {
            // Compile the expression
            node.Accept(this);
            
            // Save literals
            LastMethodLiterals = expressionScope.Literals;
        }
        finally
        {
            _context.PopScope();
        }
    }
    
    /// <summary>
    /// Generates the JSON output in the expected format.
    /// </summary>
    private string GenerateJsonOutput()
    {
        var output = new
        {
            bytecode = Bytecode.Select(b => (int)b).ToArray(),  // Convert bytes to int array
            literals = LastMethodLiterals.Select(ConvertLiteralForJson).ToArray(),
            numArgs = _methodArgCount,
            numTemps = _methodTempCount,
            stackDepth = _maxStackDepth,
            primitive = _primitiveNumber,
            source = _processorContext?.SourceCode ?? string.Empty
        };
        
        var options = new JsonSerializerOptions
        {
            WriteIndented = true,
            PropertyNamingPolicy = JsonNamingPolicy.CamelCase
        };
        
        return JsonSerializer.Serialize(output, options);
    }
    
    /// <summary>
    /// Converts a literal object to its JSON representation.
    /// </summary>
    private static object ConvertLiteralForJson(object literal) => literal switch
    {
        Symbol sym => $"#{sym.Name}",
        Association assoc => $"Association(key: #{assoc.Key}, value: {assoc.Value ?? "null"})",
        object[] array => array.Select(ConvertLiteralForJson).ToArray(),
        _ => literal
    };
    
    #endregion

    #region Visitor Implementation - Program Structure

    /// <inheritdoc/>
    public object? VisitProgram(ProgramNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Process all elements in the program
        foreach (var element in node.Elements)
        {
            element.Accept(this);
        }
        
        // Add final return if not already present
        if (_bytecode.Count == 0 || !IsReturnInstruction(_bytecode[^1]))
        {
            EmitReturnTop();
        }
        
        return null;
    }

    /// <inheritdoc/>
    public object? VisitClassDefinition(ClassDefinitionNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Class definitions are handled at a higher level
        // This visitor focuses on bytecode generation
        return null;
    }

    /// <inheritdoc/>
    public object? VisitMethodDefinition(MethodDefinitionNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Reset state for new method
        _bytecode.Clear();
        _currentStackDepth = 0;
        _maxStackDepth = 0;
        
        // Store method metadata if processing via IAstProcessor
        if (_processorContext != null)
        {
            _methodArgCount = node.Arguments.Length;
            _methodTempCount = node.Temporaries.Length;
            _primitiveNumber = node.Primitive?.PrimitiveNumber;
        }
        
        // Create method scope
        var instanceVars = _context.IsClassMethod 
            ? [] 
            : _context.ComputeInheritedInstanceVariables(_context.CurrentClass?.Name ?? "");
            
        var methodScope = new CompilationScope
        {
            Type = ScopeType.Method,
            Arguments = node.Arguments.Select(a => a.Name).ToList(),
            Temporaries = node.Temporaries.Select(t => t.Name).ToList(),
            InstanceVariables = instanceVars,
            ClassVariables = _context.CurrentClass?.ClassVariables ?? []
        };
        
        _currentScope = methodScope;
        _context.PushScope(methodScope);
        
        try
        {
            // Handle primitive methods
            // Note: Primitives are stored as metadata in CompiledMethod.PrimitiveIndex
            // They do NOT generate any bytecode - only the fallback code is compiled
            
            // Visit method body
            node.Body.Accept(this);
            
            // Ensure method ends with return
            if (_bytecode.Count == 0 || !IsReturnInstruction(_bytecode[^1]))
            {
                EmitReturnSelf();
            }
            
            // Save literals before clearing scope
            LastMethodLiterals = methodScope.Literals;
        }
        finally
        {
            _context.PopScope();
            _currentScope = null;
        }
        
        return null;
    }

    #endregion

    #region Visitor Implementation - Statements

    /// <inheritdoc/>
    public object? VisitStatementList(StatementListNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Visit each statement
        for (int i = 0; i < node.Statements.Length; i++)
        {
            var statement = node.Statements[i];
            statement.Accept(this);
            
            // Pop intermediate results except for the last statement
            // Note: Assignments do not leave values on the stack, so we only pop
            // for non-assignment expression statements
            if (i < node.Statements.Length - 1 && 
                statement is ExpressionStatementNode exprStmt && 
                !IsReturnStatement(statement) &&
                exprStmt.Expression is not AssignmentNode)
            {
                EmitPop();
            }
        }
        
        return null;
    }

    /// <inheritdoc/>
    public object? VisitReturnStatement(ReturnStatementNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Evaluate the return expression
        node.Expression.Accept(this);
        
        // Emit appropriate return instruction
        if (IsInBlockContext())
        {
            EmitBlockReturn();
        }
        else
        {
            EmitReturnTop();
        }
        
        return null;
    }

    /// <inheritdoc/>
    public object? VisitExpressionStatement(ExpressionStatementNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Simply evaluate the expression
        node.Expression.Accept(this);
        return null;
    }

    #endregion

    #region Visitor Implementation - Expressions

    /// <inheritdoc/>
    public object? VisitAssignment(AssignmentNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Evaluate the value expression
        node.Value.Accept(this);
        
        // Store to variable
        EmitStoreToVariable(node.Variable);
        
        // Note: Assignments in Smalltalk-80 do NOT leave a value on the stack.
        // The stored value is consumed by the store operation.
        // If an assignment is used as an expression (which is rare), 
        // the compiler would need to handle that specially.
        
        return null;
    }

    /// <inheritdoc/>
    public object? VisitCascade(CascadeNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Evaluate receiver once
        node.Receiver.Accept(this);
        
        // Send each message, duplicating receiver for all but last
        var messageCount = node.Messages.Length;
        for (int i = 0; i < messageCount; i++)
        {
            if (i < messageCount - 1)
            {
                EmitDuplicate(); // Keep receiver for next message
            }
            
            var message = node.Messages[i];
            EmitMessage(message);
            
            if (i < messageCount - 1)
            {
                EmitPop(); // Discard intermediate results
            }
        }
        
        return null;
    }

    /// <inheritdoc/>
    public object? VisitMessageSend(MessageSendNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Debug output to understand what's happening
        Console.WriteLine($"[DEBUG] VisitMessageSend called:");
        Console.WriteLine($"  - Node type: {node.GetType().Name}");
        Console.WriteLine($"  - Node.Message is null: {node.Message == null}");
        if (node.Message != null)
        {
            var debugSelector = node.Message.GetSelector();
            Console.WriteLine($"  - Selector from node.Message: '{debugSelector}'");
            Console.WriteLine($"  - GetSelector() result: '{node.Message.GetSelector()}'");
        }
        else
        {
            Console.WriteLine($"  - Cannot get selector - Message is null");
        }
        
        // Try to inline conditional messages first
        if (TryInlineConditional(node))
        {
            return null;
        }
        
        // Handle special super sends
        bool isSuper = node.Receiver is SuperLiteralNode;
        
        // Evaluate receiver
        node.Receiver.Accept(this);
        
        // Get message details
        var selector = node.Message?.GetSelector() ?? "";
        var arguments = node.Message?.GetArguments() ?? [];
        
        // Evaluate arguments
        foreach (var arg in arguments)
        {
            arg.Accept(this);
        }
        
        // Emit send instruction
        EmitSend(selector, arguments.Length, isSuper);
        
        return null;
    }

    /// <inheritdoc/>
    public object? VisitBlock(BlockNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Create block context
        var blockContext = new BlockContext
        {
            StartPosition = _bytecode.Count,
            Arguments = node.Arguments.Select(a => a.Name).ToList(),
            Temporaries = node.Temporaries.Select(t => t.Name).ToList()
        };
        
        _blockContexts.Push(blockContext);
        
        // Create block scope
        var blockScope = new CompilationScope
        {
            Type = ScopeType.Block,
            Arguments = blockContext.Arguments,
            Temporaries = blockContext.Temporaries,
            ParentScope = CurrentScope
        };
        
        _context.PushScope(blockScope);
        
        try
        {
            // Emit block creation bytecode sequence
            EmitPushBlock(node.Arguments.Length);
            
            // Jump around block body (block creation leaves block on stack)
            var jumpIndex = EmitJump(0); // Will be fixed up
            
            // Mark block body start
            var blockStartPos = _bytecode.Count;
            blockContext.BodyStart = blockStartPos;
            
            // Compile block body
            node.Body.Accept(this);
            
            // Ensure block ends with block return (bytecode 125)
            if (!IsReturnInstruction(_bytecode[^1]))
            {
                EmitBlockReturn(); // bytecode 125
            }
            
            // Calculate block size and patch jump
            var blockSize = _bytecode.Count - blockStartPos;
            PatchBlockJump(jumpIndex, blockSize);
        }
        finally
        {
            _blockContexts.Pop();
            _context.PopScope();
        }
        
        return null;
    }

    /// <inheritdoc/>
    public object? VisitVariable(VariableNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        EmitLoad(node.Name);
        return null;
    }

    #endregion

    #region Visitor Implementation - Literals

    /// <inheritdoc/>
    public object? VisitNumberLiteral(NumberLiteralNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Handle small integers specially
        if (!node.IsFloat && node.Value is int intValue && intValue >= -1 && intValue <= 2)
        {
            EmitPushSmallInteger(intValue);
        }
        else
        {
            EmitPushLiteral(node.Value);
        }
        
        return null;
    }

    /// <inheritdoc/>
    public object? VisitStringLiteral(StringLiteralNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        EmitPushLiteral(node.Value);
        return null;
    }

    /// <inheritdoc/>
    public object? VisitSymbolLiteral(SymbolLiteralNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        EmitPushLiteral(new Symbol(node.Value));
        return null;
    }

    /// <inheritdoc/>
    public object? VisitArrayLiteral(ArrayLiteralNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Convert elements to literal values
        var elements = node.Elements.Select(ConvertToLiteral).ToArray();
        EmitPushLiteral(elements);
        return null;
    }

    /// <inheritdoc/>
    public object? VisitCharacterLiteral(CharacterLiteralNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        EmitPushLiteral(node.Value);
        return null;
    }

    /// <inheritdoc/>
    public object? VisitBooleanLiteral(BooleanLiteralNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        if (node.Value)
            EmitPushTrue();
        else
            EmitPushFalse();
        
        return null;
    }

    /// <inheritdoc/>
    public object? VisitNilLiteral(NilLiteralNode node)
    {
        EmitPushNil();
        return null;
    }

    /// <inheritdoc/>
    public object? VisitSelfLiteral(SelfLiteralNode node)
    {
        EmitPushSelf();
        return null;
    }

    /// <inheritdoc/>
    public object? VisitSuperLiteral(SuperLiteralNode node)
    {
        EmitPushSelf(); // Super uses self as receiver
        return null;
    }

    #endregion

    #region Visitor Implementation - Message Components

    /// <inheritdoc/>
    public object? VisitUnaryMessage(UnaryMessageNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Messages are handled by MessageSendNode
        return null;
    }

    /// <inheritdoc/>
    public object? VisitBinaryMessage(BinaryMessageNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Messages are handled by MessageSendNode
        return null;
    }

    /// <inheritdoc/>
    public object? VisitKeywordMessage(KeywordMessageNode node)
    {
        ArgumentNullException.ThrowIfNull(node);
        
        // Messages are handled by MessageSendNode
        return null;
    }

    #endregion

    #region Visitor Implementation - Declarations

    /// <inheritdoc/>
    public object? VisitTemporaryDeclaration(TemporaryDeclarationNode node)
    {
        // Declarations are handled when creating scope
        return null;
    }

    /// <inheritdoc/>
    public object? VisitBlockArgument(BlockArgumentNode node)
    {
        // Arguments are handled when creating scope
        return null;
    }

    /// <inheritdoc/>
    public object? VisitMethodArgument(MethodArgumentNode node)
    {
        // Arguments are handled when creating scope
        return null;
    }

