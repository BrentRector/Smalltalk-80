        /// Gets the block arguments.
        /// </summary>
        public IReadOnlyList<string> Arguments { get; init; } = [];
        
        /// <summary>
        /// Gets the block temporaries.
        /// </summary>
        public IReadOnlyList<string> Temporaries { get; init; } = [];
    }
