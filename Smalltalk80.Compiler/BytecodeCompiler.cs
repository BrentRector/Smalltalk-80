        }
        
        // Push operations
        
        public void PushReceiverVariable(int index)
        {
            if (index <= 15)
            {
                EmitWithOffset(Bytecode.PUSH_IVAR_0, index); // 0x00-0x0F
            }
            else
            {
                Emit(Bytecode.EXTENDED_PREFIX); // 0x80
                Emit(ExtendedSubOp.PUSH_IVAR);
                Emit((byte)index);
            }
        }

