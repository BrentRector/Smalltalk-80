using System.Text;
using Smalltalk80.Compiler.AST;

namespace Smalltalk80.Compiler.CodeGen;

/// <summary>
/// Extracts all symbol literals and string literals from Smalltalk class definitions.
/// This is used to generate a complete list of literals that need to be pre-interned
/// during cold start to avoid creating temporary garbage objects.
/// </summary>
public sealed class LiteralExtractor
{
    private readonly HashSet<string> _symbols = new(StringComparer.Ordinal);
    private readonly HashSet<string> _strings = new(StringComparer.Ordinal);

    /// <summary>
    /// Extracts all literals from a compilation result.
    /// </summary>
    /// <param name="result">The compilation result containing classes and initialization expressions.</param>
    public void Extract(CompilationResult result)
    {
        ArgumentNullException.ThrowIfNull(result);

        // Extract from class definitions
        foreach (var classNode in result.Classes)
        {
            ExtractFromClass(classNode);
        }

        // Extract from initialization expressions
        foreach (var initExpr in result.InitializationExpressions)
        {
            ExtractFromLiterals(initExpr.Literals);
        }
    }

    /// <summary>
    /// Extracts literals from a class definition including all methods.
    /// </summary>
    private void ExtractFromClass(ClassDefinitionNode classNode)
    {
        // Class name is a symbol
        _symbols.Add(classNode.Name);

        // Superclass name is a symbol
        if (!string.IsNullOrEmpty(classNode.Superclass) && classNode.Superclass != "nil")
        {
            _symbols.Add(classNode.Superclass);
        }

        // Instance variable names are symbols
        foreach (var varName in classNode.InstanceVariables)
        {
            _symbols.Add(varName);
        }

        // Class variable names are symbols
        foreach (var varName in classNode.ClassVariables)
        {
            _symbols.Add(varName);
        }

        // Pool dictionary names are symbols
        foreach (var poolName in classNode.PoolDictionaries)
        {
            _symbols.Add(poolName);
        }

        // Extract from instance methods
        foreach (var method in classNode.Methods)
        {
            ExtractFromMethod(method);
        }

        // Extract from class methods
        foreach (var method in classNode.ClassMethods)
        {
            ExtractFromMethod(method);
        }
    }

    /// <summary>
    /// Extracts literals from a method definition.
    /// </summary>
    private void ExtractFromMethod(MethodDefinitionNode method)
    {
        // Method selector is a symbol
        _symbols.Add(method.Selector);

        // Extract from method literals
        ExtractFromLiterals(method.Literals);
    }

    /// <summary>
    /// Recursively extracts literals from a list of literal objects.
    /// These are already in the compiled format from the bytecode compiler.
    /// </summary>
    private void ExtractFromLiterals(List<object> literals)
    {
        foreach (var literal in literals)
        {
            switch (literal)
            {
                case Symbol sym:
                    // Symbol object from bytecode compiler (message selectors, etc.)
                    _symbols.Add(sym.Value);
                    break;

                case string s when s.StartsWith("#"):
                    // Symbol literal - remove the # prefix
                    _symbols.Add(s.Substring(1));
                    break;

                case string s when s.StartsWith("Association("):
                    // Association literal - extract key (which is always a symbol)
                    // Format: "Association(key:symbolName,value:...)"
                    var match = System.Text.RegularExpressions.Regex.Match(s, @"Association\(key:([^,]+),value:");
                    if (match.Success)
                    {
                        _symbols.Add(match.Groups[1].Value);
                    }
                    break;

                case string s:
                    // String literal
                    _strings.Add(s);
                    break;

                case List<object> nestedList:
                    // Nested array literal
                    ExtractFromLiterals(nestedList);
                    break;

                // Numbers, booleans, etc. don't need pre-interning
                default:
                    break;
            }
        }
    }

    /// <summary>
    /// Generates C# code containing all extracted symbols as a pre-intern list.
    /// </summary>
    /// <returns>C# source code with symbol arrays.</returns>
    public string GenerateCSharpCode()
    {
        var output = new StringBuilder();

        // File header
        output.AppendLine("// <auto-generated>");
        output.AppendLine("//     This code was generated by the Smalltalk80 Compiler.");
        output.AppendLine("//     Contains all symbols and string literals used in cold start classes.");
        output.AppendLine("//     Changes to this file may cause incorrect behavior and will be lost if");
        output.AppendLine("//     the code is regenerated.");
        output.AppendLine("// </auto-generated>");
        output.AppendLine();
        output.AppendLine("namespace Smalltalk80.Interpreter.Generated;");
        output.AppendLine();
        output.AppendLine("/// <summary>");
        output.AppendLine("/// Contains all symbols and string literals extracted from cold start class definitions.");
        output.AppendLine("/// These should be pre-interned before USTable creation to avoid garbage creation.");
        output.AppendLine("/// </summary>");
        output.AppendLine("public static class ColdStartLiterals");
        output.AppendLine("{");

        // Generate symbols array
        output.AppendLine("    /// <summary>");
        output.AppendLine("    /// All symbols used in cold start classes (selectors, class names, variable names, etc.).");
        output.AppendLine($"    /// Total count: {_symbols.Count}");
        output.AppendLine("    /// </summary>");
        output.AppendLine("    public static readonly string[] Symbols = {");

        var sortedSymbols = _symbols.ToList();
        sortedSymbols.Sort(StringComparer.Ordinal);
        for (int i = 0; i < sortedSymbols.Count; i++)
        {
            var symbol = sortedSymbols[i];
            var escaped = EscapeCSharpString(symbol);
            var comma = i < sortedSymbols.Count - 1 ? "," : "";
            output.AppendLine($"        \"{escaped}\"{comma}");
        }

        output.AppendLine("    };");
        output.AppendLine();

        // Generate strings array
        output.AppendLine("    /// <summary>");
        output.AppendLine("    /// All string literals used in cold start classes.");
        output.AppendLine($"    /// Total count: {_strings.Count}");
        output.AppendLine("    /// </summary>");
        output.AppendLine("    public static readonly string[] Strings = {");

        var sortedStrings = _strings.ToList();
        sortedStrings.Sort(StringComparer.Ordinal);
        for (int i = 0; i < sortedStrings.Count; i++)
        {
            var str = sortedStrings[i];
            var escaped = EscapeCSharpString(str);
            var comma = i < sortedStrings.Count - 1 ? "," : "";
            output.AppendLine($"        \"{escaped}\"{comma}");
        }

        output.AppendLine("    };");
        output.AppendLine("}");

        return output.ToString();
    }

    /// <summary>
    /// Escapes a string for use in C# source code.
    /// </summary>
    private static string EscapeCSharpString(string input)
    {
        return input
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\n", "\\n")
            .Replace("\r", "\\r")
            .Replace("\t", "\\t");
    }

    /// <summary>
    /// Gets statistics about extracted literals.
    /// </summary>
    public (int SymbolCount, int StringCount) GetStatistics()
    {
        return (_symbols.Count, _strings.Count);
    }
}
