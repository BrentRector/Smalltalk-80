using System.Text;
using Smalltalk80.Compiler.AST;

namespace Smalltalk80.Compiler.CodeGen;

/// <summary>
/// Generates C# memory layout definitions from Smalltalk class definitions.
/// </summary>
public sealed class LayoutGenerator
{
    private readonly Dictionary<string, ClassInfo> _classInfoMap = new(StringComparer.Ordinal);
    private readonly HashSet<string> _processedClasses = new(StringComparer.Ordinal);
    private readonly StringBuilder _output = new();

    /// <summary>
    /// Represents collected information about a Smalltalk class.
    /// </summary>
    private sealed record ClassInfo(
        string Name,
        string? SuperclassName,
        string SubclassKind,
        List<string> InstanceVariables,
        List<string> AllInstanceVariables,
        int TotalInstanceVarCount
    );

    /// <summary>
    /// Generates C# layout code from a list of Smalltalk class definitions.
    /// </summary>
    /// <param name="classes">The list of class definitions to process.</param>
    /// <returns>The generated C# code as a string.</returns>
    /// <exception cref="ArgumentNullException">Thrown when classes is null.</exception>
    public string Generate(List<ClassDefinitionNode> classes)
    {
        ArgumentNullException.ThrowIfNull(classes);

        // Build class information map and inheritance hierarchy
        BuildClassInfoMap(classes);

        // Generate file header
        GenerateFileHeader();

        // Generate layouts in dependency order (superclasses before subclasses)
        foreach (var classDefNode in classes)
        {
            GenerateClassLayout(classDefNode.Name);
        }

        // No need to close namespace - using file-scoped namespace declaration

        return _output.ToString();
    }

    /// <summary>
    /// Builds a map of class information including inherited variables.
    /// </summary>
    /// <param name="classes">The class definitions to analyze.</param>
    private void BuildClassInfoMap(List<ClassDefinitionNode> classes)
    {
        // First pass: create basic class info
        foreach (var classNode in classes)
        {
            var name = classNode.Name;
            var superclass = string.IsNullOrEmpty(classNode.Superclass) || classNode.Superclass == "nil"
                ? null
                : classNode.Superclass;

            var instanceVars = classNode.InstanceVariables ?? [];
            var subclassKind = string.IsNullOrEmpty(classNode.SubclassKind)
                ? "subclass:"
                : classNode.SubclassKind;

            _classInfoMap[name] = new ClassInfo(
                Name: name,
                SuperclassName: superclass,
                SubclassKind: subclassKind,
                InstanceVariables: instanceVars,
                AllInstanceVariables: [], // Will be filled in second pass
                TotalInstanceVarCount: 0  // Will be calculated in second pass
            );
        }

        // Second pass: calculate all instance variables including inherited ones
        foreach (var className in _classInfoMap.Keys.ToList())
        {
            var allVars = CollectAllInstanceVariables(className);
            var info = _classInfoMap[className];

            _classInfoMap[className] = info with
            {
                AllInstanceVariables = allVars,
                TotalInstanceVarCount = allVars.Count
            };
        }
    }

    /// <summary>
    /// Collects all instance variables for a class including inherited ones.
    /// </summary>
    /// <param name="className">The name of the class.</param>
    /// <returns>List of all instance variables in inheritance order.</returns>
    private List<string> CollectAllInstanceVariables(string className)
    {
        var result = new List<string>();
        var currentClass = className;
        var classChain = new Stack<string>();

        // Walk up the inheritance chain
        while (!string.IsNullOrEmpty(currentClass) && _classInfoMap.TryGetValue(currentClass, out var info))
        {
            classChain.Push(currentClass);
            currentClass = info.SuperclassName;
        }

        // Add variables from root to leaf (superclass variables come first)
        while (classChain.Count > 0)
        {
            var cls = classChain.Pop();
            if (_classInfoMap.TryGetValue(cls, out var classInfo))
            {
                result.AddRange(classInfo.InstanceVariables);
            }
        }

        return result;
    }

    /// <summary>
    /// Generates the file header with auto-generated warning and using statements.
    /// </summary>
    private void GenerateFileHeader()
    {
        _output.AppendLine("// <auto-generated>");
        _output.AppendLine("//     This code was generated by the Smalltalk80 Compiler.");
        _output.AppendLine("//     Changes to this file may cause incorrect behavior and will be lost if");
        _output.AppendLine("//     the code is regenerated.");
        _output.AppendLine("// </auto-generated>");
        _output.AppendLine();
        _output.AppendLine("using Smalltalk80.Interpreter.Core.Objects;");
        _output.AppendLine("using Smalltalk80.Interpreter.Core.Values;");
        _output.AppendLine("using Smalltalk80.Interpreter.Memory;");
        _output.AppendLine();
        _output.AppendLine("namespace Smalltalk80.Interpreter.Generated.Layouts;");
        _output.AppendLine();
    }

    /// <summary>
    /// Generates the layout code for a specific class.
    /// </summary>
    /// <param name="className">The name of the class to generate.</param>
    private void GenerateClassLayout(string className)
    {
        // Skip if already processed
        if (_processedClasses.Contains(className))
            return;

        if (!_classInfoMap.TryGetValue(className, out var classInfo))
            return;

        // Generate superclass first if it exists
        if (!string.IsNullOrEmpty(classInfo.SuperclassName))
        {
            GenerateClassLayout(classInfo.SuperclassName);
        }

        // Generate interface
        GenerateInterface(classInfo);

        // Generate struct implementation
        GenerateStruct(classInfo);

        _processedClasses.Add(className);
    }

    /// <summary>
    /// Generates the interface definition for a class.
    /// </summary>
    /// <param name="classInfo">The class information.</param>
    private void GenerateInterface(ClassInfo classInfo)
    {
        var interfaceName = $"IST{classInfo.Name}";
        var baseInterface = string.IsNullOrEmpty(classInfo.SuperclassName)
            ? ""
            : $" : IST{classInfo.SuperclassName}";

        _output.AppendLine($"/// <summary>");
        _output.AppendLine($"/// Interface for {classInfo.Name} memory layout.");
        _output.AppendLine($"/// </summary>");
        _output.AppendLine($"public interface {interfaceName}{baseInterface}");
        _output.AppendLine("{");

        // Add properties for this class's instance variables only
        foreach (var varName in classInfo.InstanceVariables)
        {
            var propertyName = ToPascalCase(varName);
            _output.AppendLine($"    /// <summary>");
            _output.AppendLine($"    /// Gets or sets the {varName} instance variable.");
            _output.AppendLine($"    /// </summary>");
            _output.AppendLine($"    SObjectRef {propertyName} {{ get; set; }}");
        }

        // Add AsRef property if this is the root (Object)
        if (string.IsNullOrEmpty(classInfo.SuperclassName))
        {
            _output.AppendLine($"    /// <summary>");
            _output.AppendLine($"    /// Gets the underlying object reference.");
            _output.AppendLine($"    /// </summary>");
            _output.AppendLine($"    SObjectRef AsRef {{ get; }}");
        }

        _output.AppendLine("}");
        _output.AppendLine();
    }

    /// <summary>
    /// Generates the struct implementation for a class.
    /// </summary>
    /// <param name="classInfo">The class information.</param>
    private void GenerateStruct(ClassInfo classInfo)
    {
        var structName = $"ST{classInfo.Name}";
        var interfaceName = $"IST{classInfo.Name}";

        _output.AppendLine($"/// <summary>");
        _output.AppendLine($"/// Memory layout for {classInfo.Name} objects.");
        _output.AppendLine($"/// </summary>");
        _output.AppendLine($"public readonly struct {structName} : {interfaceName}");
        _output.AppendLine("{");

        // Field for object reference
        _output.AppendLine("    private readonly SObjectRef _ref;");
        _output.AppendLine();

        // AsRef property
        _output.AppendLine("    /// <summary>");
        _output.AppendLine("    /// Gets the underlying object reference.");
        _output.AppendLine("    /// </summary>");
        _output.AppendLine("    public SObjectRef AsRef => _ref;");
        _output.AppendLine();

        // Constructor
        _output.AppendLine("    /// <summary>");
        _output.AppendLine($"    /// Initializes a new instance of <see cref=\"{structName}\"/>.");
        _output.AppendLine("    /// </summary>");
        _output.AppendLine("    /// <param name=\"objectRef\">The object reference.</param>");
        _output.AppendLine($"    public {structName}(SObjectRef objectRef) => _ref = objectRef;");
        _output.AppendLine();

        // Implicit conversions
        _output.AppendLine("    /// <summary>");
        _output.AppendLine($"    /// Implicitly converts a <see cref=\"{structName}\"/> to <see cref=\"SObjectRef\"/>.");
        _output.AppendLine("    /// </summary>");
        _output.AppendLine($"    public static implicit operator SObjectRef({structName} obj) => obj._ref;");
        _output.AppendLine();
        _output.AppendLine("    /// <summary>");
        _output.AppendLine($"    /// Implicitly converts a <see cref=\"SObjectRef\"/> to <see cref=\"{structName}\"/>.");
        _output.AppendLine("    /// </summary>");
        _output.AppendLine($"    public static implicit operator {structName}(SObjectRef r) => new(r);");

        // Generate properties for ALL instance variables (inherited + own)
        if (classInfo.AllInstanceVariables.Count > 0)
        {
            _output.AppendLine();

            // Group variables by declaring class for documentation
            var inheritedVarCount = classInfo.TotalInstanceVarCount - classInfo.InstanceVariables.Count;

            for (var i = 0; i < classInfo.AllInstanceVariables.Count; i++)
            {
                var varName = classInfo.AllInstanceVariables[i];
                var propertyName = ToPascalCase(varName);
                var isInherited = i < inheritedVarCount;

                _output.AppendLine();

                if (isInherited && i == 0)
                {
                    _output.AppendLine($"    // Inherited instance variables");
                }
                else if (!isInherited && i == inheritedVarCount)
                {
                    _output.AppendLine($"    // Own instance variables");
                }

                _output.AppendLine($"    /// <summary>");
                _output.AppendLine($"    /// Gets or sets the {varName} instance variable at offset {i}.");
                _output.AppendLine($"    /// </summary>");
                _output.AppendLine($"    public SObjectRef {propertyName}");
                _output.AppendLine("    {");
                _output.AppendLine($"        get => _ref.GetInstanceVariable({i});");
                _output.AppendLine($"        set => _ref.SetInstanceVariable({i}, value);");
                _output.AppendLine("    }");
            }
        }

        // Constants
        _output.AppendLine();
        _output.AppendLine($"    /// <summary>");
        _output.AppendLine($"    /// The total number of instance variables for {structName}.");
        _output.AppendLine($"    /// </summary>");
        _output.AppendLine($"    public const int InstanceVarCount = {classInfo.TotalInstanceVarCount};");

        // Determine format from subclass kind - check CompiledMethod special case first
        var format = classInfo.Name == "CompiledMethod"
            ? "ObjectFormat.CompiledMethod"
            : classInfo.SubclassKind switch
            {
                "subclass:" => "ObjectFormat.FixedPointer",
                "variableSubclass:" => "ObjectFormat.PointerIndexed",
                "variableByteSubclass:" => "ObjectFormat.ByteIndexed",
                "variableWordSubclass:" => "ObjectFormat.WordIndexed",
                _ => "ObjectFormat.FixedPointer"
            };

        _output.AppendLine();
        _output.AppendLine($"    /// <summary>");
        _output.AppendLine($"    /// The object format for {structName}.");
        _output.AppendLine($"    /// </summary>");
        _output.AppendLine($"    public const ObjectFormat IndexedFormat = {format};");

        // Generate special accessors based on class type
        GenerateSpecialAccessors(classInfo);

        // Generate convenience properties
        GenerateConvenienceProperties(classInfo);

        _output.AppendLine("}");
        _output.AppendLine();
    }

    /// <summary>
    /// Generates special accessors for specific class types.
    /// </summary>
    /// <param name="classInfo">The class information.</param>
    private void GenerateSpecialAccessors(ClassInfo classInfo)
    {
        // Handle IdentityDictionary and MethodDictionary with parallel array structure
        if (classInfo.Name is "IdentityDictionary" or "MethodDictionary")
        {
            GenerateDictionaryAccessors(classInfo);
        }
        // Handle Context classes with semantic accessors
        else if (classInfo.Name is "MethodContext" or "BlockContext" or "ContextPart")
        {
            GenerateContextAccessors(classInfo);
        }
        // Handle CompiledMethod special properties
        else if (classInfo.Name == "CompiledMethod")
        {
            GenerateCompiledMethodAccessors(classInfo);
        }
        // Default indexers for other variable classes
        else
        {
            GenerateDefaultIndexers(classInfo);
        }
    }

    /// <summary>
    /// Generates parallel array accessors for dictionary classes.
    /// </summary>
    /// <param name="classInfo">The class information.</param>
    private void GenerateDictionaryAccessors(ClassInfo classInfo)
    {
        // Find the valueArray instance variable index
        var valueArrayIndex = classInfo.AllInstanceVariables.IndexOf("valueArray");

        if (valueArrayIndex == -1)
        {
            // Fallback to default indexers if valueArray not found
            GenerateDefaultIndexers(classInfo);
            return;
        }

        _output.AppendLine();
        _output.AppendLine("    /// <summary>");
        _output.AppendLine("    /// Gets the keys collection for indexed access.");
        _output.AppendLine("    /// </summary>");
        _output.AppendLine("    public KeysCollection Keys => new KeysCollection(_ref);");
        _output.AppendLine();
        _output.AppendLine("    /// <summary>");
        _output.AppendLine("    /// Gets the values collection for indexed access.");
        _output.AppendLine("    /// </summary>");
        _output.AppendLine("    public ValuesCollection Values => new ValuesCollection(_ref);");

        // Generate nested KeysCollection struct
        _output.AppendLine();
        _output.AppendLine("    /// <summary>");
        _output.AppendLine("    /// Collection for accessing dictionary keys.");
        _output.AppendLine("    /// </summary>");
        _output.AppendLine("    public readonly struct KeysCollection");
        _output.AppendLine("    {");
        _output.AppendLine("        private readonly SObjectRef _dictRef;");
        _output.AppendLine();
        _output.AppendLine("        internal KeysCollection(SObjectRef dictRef) => _dictRef = dictRef;");
        _output.AppendLine();
        _output.AppendLine("        /// <summary>");
        _output.AppendLine("        /// Gets or sets the key at the specified index.");
        _output.AppendLine("        /// </summary>");
        _output.AppendLine("        public SObjectRef this[int index]");
        _output.AppendLine("        {");
        _output.AppendLine("            get => _dictRef.GetIndexedPointer(index);");
        _output.AppendLine("            set => _dictRef.SetIndexedPointer(index, value);");
        _output.AppendLine("        }");
        _output.AppendLine();
        _output.AppendLine("        /// <summary>");
        _output.AppendLine("        /// Gets the number of keys.");
        _output.AppendLine("        /// </summary>");
        _output.AppendLine("        public int Length => _dictRef.GetIndexedSize();");
        _output.AppendLine("    }");

        // Generate nested ValuesCollection struct - need to pass valueArrayIndex as const
        _output.AppendLine();
        _output.AppendLine("    /// <summary>");
        _output.AppendLine("    /// Collection for accessing dictionary values.");
        _output.AppendLine("    /// </summary>");
        _output.AppendLine("    public readonly struct ValuesCollection");
        _output.AppendLine("    {");
        _output.AppendLine("        private readonly SObjectRef _dictRef;");
        _output.AppendLine($"        private const int ValueArrayIndex = {valueArrayIndex};");
        _output.AppendLine();
        _output.AppendLine("        internal ValuesCollection(SObjectRef dictRef) => _dictRef = dictRef;");
        _output.AppendLine();
        _output.AppendLine("        /// <summary>");
        _output.AppendLine("        /// Gets or sets the value at the specified index.");
        _output.AppendLine("        /// </summary>");
        _output.AppendLine("        public SObjectRef this[int index]");
        _output.AppendLine("        {");
        _output.AppendLine("            get");
        _output.AppendLine("            {");
        _output.AppendLine("                var valueArrayRef = _dictRef.GetInstanceVariable(ValueArrayIndex);");
        _output.AppendLine("                STArray valueArray = valueArrayRef;");
        _output.AppendLine("                return valueArray[index];");
        _output.AppendLine("            }");
        _output.AppendLine("            set");
        _output.AppendLine("            {");
        _output.AppendLine("                var valueArrayRef = _dictRef.GetInstanceVariable(ValueArrayIndex);");
        _output.AppendLine("                STArray valueArray = valueArrayRef;");
        _output.AppendLine("                valueArray[index] = value;");
        _output.AppendLine("            }");
        _output.AppendLine("        }");
        _output.AppendLine();
        _output.AppendLine("        /// <summary>");
        _output.AppendLine("        /// Gets the number of values.");
        _output.AppendLine("        /// </summary>");
        _output.AppendLine("        public int Length");
        _output.AppendLine("        {");
        _output.AppendLine("            get");
        _output.AppendLine("            {");
        _output.AppendLine("                var valueArrayRef = _dictRef.GetInstanceVariable(ValueArrayIndex);");
        _output.AppendLine("                STArray valueArray = valueArrayRef;");
        _output.AppendLine("                return valueArray.Length;");
        _output.AppendLine("            }");
        _output.AppendLine("        }");
        _output.AppendLine("    }");
    }

    /// <summary>
    /// Generates semantic accessors for context classes.
    /// </summary>
    /// <param name="classInfo">The class information.</param>
    private void GenerateContextAccessors(ClassInfo classInfo)
    {
        _output.AppendLine();
        _output.AppendLine("    /// <summary>");
        _output.AppendLine("    /// Gets a temporary variable at the specified index.");
        _output.AppendLine("    /// </summary>");
        _output.AppendLine("    /// <param name=\"index\">The index of the temporary variable.</param>");
        _output.AppendLine("    /// <returns>The temporary variable value.</returns>");
        _output.AppendLine("    public SObjectRef GetTemporary(int index) => _ref.GetIndexedPointer(index);");
        _output.AppendLine();
        _output.AppendLine("    /// <summary>");
        _output.AppendLine("    /// Sets a temporary variable at the specified index.");
        _output.AppendLine("    /// </summary>");
        _output.AppendLine("    /// <param name=\"index\">The index of the temporary variable.</param>");
        _output.AppendLine("    /// <param name=\"value\">The value to set.</param>");
        _output.AppendLine("    public void SetTemporary(int index, SObjectRef value) => _ref.SetIndexedPointer(index, value);");
        _output.AppendLine();
        _output.AppendLine("    /// <summary>");
        _output.AppendLine("    /// Gets a stack slot at the specified index.");
        _output.AppendLine("    /// </summary>");
        _output.AppendLine("    /// <param name=\"index\">The index of the stack slot.</param>");
        _output.AppendLine("    /// <returns>The stack slot value.</returns>");
        _output.AppendLine("    public SObjectRef GetStackSlot(int index) => _ref.GetIndexedPointer(index);");
        _output.AppendLine();
        _output.AppendLine("    /// <summary>");
        _output.AppendLine("    /// Sets a stack slot at the specified index.");
        _output.AppendLine("    /// </summary>");
        _output.AppendLine("    /// <param name=\"index\">The index of the stack slot.</param>");
        _output.AppendLine("    /// <param name=\"value\">The value to set.</param>");
        _output.AppendLine("    public void SetStackSlot(int index, SObjectRef value) => _ref.SetIndexedPointer(index, value);");
        _output.AppendLine();
        _output.AppendLine("    /// <summary>");
        _output.AppendLine("    /// Gets the number of indexed slots (temporaries and stack).");
        _output.AppendLine("    /// </summary>");
        _output.AppendLine("    public int Length => _ref.GetIndexedSize();");
    }

    /// <summary>
    /// Generates special accessors for CompiledMethod.
    /// </summary>
    /// <param name="classInfo">The class information.</param>
    private void GenerateCompiledMethodAccessors(ClassInfo classInfo)
    {
        _output.AppendLine();
        _output.AppendLine("    /// <summary>");
        _output.AppendLine("    /// Gets the length of the bytecode array.");
        _output.AppendLine("    /// </summary>");
        _output.AppendLine("    public int Length => _ref.GetIndexedSize();");
    }

    /// <summary>
    /// Generates default indexers for variable classes.
    /// </summary>
    /// <param name="classInfo">The class information.</param>
    private void GenerateDefaultIndexers(ClassInfo classInfo)
    {
        if (classInfo.SubclassKind == "variableSubclass:")
        {
            _output.AppendLine();
            _output.AppendLine("    /// <summary>");
            _output.AppendLine("    /// Gets or sets the indexed pointer at the specified index.");
            _output.AppendLine("    /// </summary>");
            _output.AppendLine("    public SObjectRef this[int index]");
            _output.AppendLine("    {");
            _output.AppendLine("        get => _ref.GetIndexedPointer(index);");
            _output.AppendLine("        set => _ref.SetIndexedPointer(index, value);");
            _output.AppendLine("    }");
            _output.AppendLine();
            _output.AppendLine("    /// <summary>");
            _output.AppendLine("    /// Gets the length of the indexed portion.");
            _output.AppendLine("    /// </summary>");
            _output.AppendLine("    public int Length => _ref.GetIndexedSize();");
        }
        else if (classInfo.SubclassKind == "variableByteSubclass:")
        {
            _output.AppendLine();
            _output.AppendLine("    /// <summary>");
            _output.AppendLine("    /// Gets or sets the indexed byte at the specified index.");
            _output.AppendLine("    /// </summary>");
            _output.AppendLine("    public byte this[int index]");
            _output.AppendLine("    {");
            _output.AppendLine("        get => _ref.GetIndexedByte(index);");
            _output.AppendLine("        set => _ref.SetIndexedByte(index, value);");
            _output.AppendLine("    }");
            _output.AppendLine();
            _output.AppendLine("    /// <summary>");
            _output.AppendLine("    /// Gets the length of the indexed portion.");
            _output.AppendLine("    /// </summary>");
            _output.AppendLine("    public int Length => _ref.GetIndexedSize();");
        }
        else if (classInfo.SubclassKind == "variableWordSubclass:")
        {
            _output.AppendLine();
            _output.AppendLine("    /// <summary>");
            _output.AppendLine("    /// Gets or sets the indexed word at the specified index.");
            _output.AppendLine("    /// </summary>");
            _output.AppendLine("    public ushort this[int index]");
            _output.AppendLine("    {");
            _output.AppendLine("        get => _ref.GetIndexedWord(index);");
            _output.AppendLine("        set => _ref.SetIndexedWord(index, value);");
            _output.AppendLine("    }");
            _output.AppendLine();
            _output.AppendLine("    /// <summary>");
            _output.AppendLine("    /// Gets the length of the indexed portion.");
            _output.AppendLine("    /// </summary>");
            _output.AppendLine("    public int Length => _ref.GetIndexedSize();");
        }
    }

    /// <summary>
    /// Generates convenience properties for specific classes.
    /// </summary>
    /// <param name="classInfo">The class information.</param>
    private void GenerateConvenienceProperties(ClassInfo classInfo)
    {
        // Add Count property for classes with tally
        if (classInfo.AllInstanceVariables.Contains("tally"))
        {
            _output.AppendLine();
            _output.AppendLine("    /// <summary>");
            _output.AppendLine("    /// Gets the count (tally converted to int).");
            _output.AppendLine("    /// </summary>");
            _output.AppendLine("    public int Count => Tally.AsSmallInteger();");
        }

        // Add convenience properties for context classes
        if (classInfo.Name is "MethodContext" or "BlockContext")
        {
            if (classInfo.AllInstanceVariables.Contains("stackp"))
            {
                _output.AppendLine();
                _output.AppendLine("    /// <summary>");
                _output.AppendLine("    /// Gets the stack pointer as an integer.");
                _output.AppendLine("    /// </summary>");
                _output.AppendLine("    public int StackPointer => Stackp.AsSmallInteger();");
            }
            if (classInfo.AllInstanceVariables.Contains("pc"))
            {
                _output.AppendLine();
                _output.AppendLine("    /// <summary>");
                _output.AppendLine("    /// Gets the program counter as an integer.");
                _output.AppendLine("    /// </summary>");
                _output.AppendLine("    public int ProgramCounter => Pc.AsSmallInteger();");
            }
        }
    }

    /// <summary>
    /// Converts a Smalltalk variable name to C# PascalCase property name.
    /// </summary>
    /// <param name="varName">The Smalltalk variable name.</param>
    /// <returns>The C# property name in PascalCase.</returns>
    private static string ToPascalCase(string varName)
    {
        if (string.IsNullOrEmpty(varName))
            return varName;

        // Handle snake_case or camelCase
        var parts = varName.Split('_', StringSplitOptions.RemoveEmptyEntries);

        if (parts.Length > 1)
        {
            // snake_case: capitalize each part
            return string.Concat(parts.Select(CapitalizeFirst));
        }

        // Regular camelCase or single word: just capitalize first letter
        return CapitalizeFirst(varName);
    }

    /// <summary>
    /// Capitalizes the first character of a string.
    /// </summary>
    /// <param name="str">The string to capitalize.</param>
    /// <returns>The string with its first character capitalized.</returns>
    private static string CapitalizeFirst(string str)
    {
        if (string.IsNullOrEmpty(str))
            return str;

        return char.ToUpperInvariant(str[0]) + str[1..];
    }
}