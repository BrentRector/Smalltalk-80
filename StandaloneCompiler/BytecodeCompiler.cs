    /// <summary>
    /// Environment for bytecode generation tracking variable indices and scope.
    /// </summary>
    public class CompilationEnvironment
    {
        /// <summary>
        /// Current scope depth (0 for method, 1+ for nested blocks).
        /// </summary>
        public int ScopeDepth { get; set; }
        
        /// <summary>
        /// Map of argument names to their indices.
        /// </summary>
        public Dictionary<string, int> Arguments { get; } = new();
        
        /// <summary>
        /// Map of temporary variable names to their indices.
        /// </summary>
        public Dictionary<string, int> Temporaries { get; } = new();
        
        /// <summary>
        /// Map of instance variable names to their indices.
        /// </summary>
        public Dictionary<string, int> InstanceVariables { get; } = new();
        
        /// <summary>
        /// Hidden temporaries for cascade receivers and scratch values.
        /// </summary>
        public Dictionary<string, int> HiddenTemporaries { get; } = new();
        
        /// <summary>
        /// Class variables (shared among all instances of a class).
        /// These are stored as Associations in the literal frame.
        /// </summary>
        public Dictionary<string, object> ClassVariables { get; } = new();
        
        /// <summary>
        /// Pool variables (shared dictionaries imported by classes).
        /// These are stored as Associations in the literal frame.
        /// </summary>
        public Dictionary<string, object> PoolVariables { get; } = new();
        
        /// <summary>
        /// Total number of arguments.
        /// </summary>
        public int ArgumentCount { get; set; }
        
        /// <summary>
        /// Total number of temporaries (including hidden).
        /// </summary>
        public int TemporaryCount { get; set; }
        
        /// <summary>
        /// Gets the index for a variable name.
        /// </summary>
        public int? GetVariableIndex(string name)
        {
            if (Arguments.TryGetValue(name, out var argIndex))
                return argIndex;
            if (Temporaries.TryGetValue(name, out var tempIndex))
                return tempIndex;
            if (HiddenTemporaries.TryGetValue(name, out var hiddenIndex))
                return hiddenIndex;
            return null;
        }
        
        /// <summary>
        /// Allocates a hidden temporary variable.
        /// </summary>
        public int AllocateHiddenTemp(string name)
        {
            if (!HiddenTemporaries.ContainsKey(name))
            {
                var index = ArgumentCount + TemporaryCount;
                HiddenTemporaries[name] = index;
                TemporaryCount++;
            }
            return HiddenTemporaries[name];
        }
    }
    
    /// <summary>
    /// Bytecode emitter that generates Blue Book bytecodes.
    /// </summary>
    public class BytecodeEmitter
    {
        private readonly List<byte> bytecodes = new();
        private readonly List<object> literals = new();
        private readonly Dictionary<object, int> literalIndex = new();
        
        /// <summary>
        /// Gets the generated bytecode array.
        /// </summary>
        public byte[] GetBytecodes() => bytecodes.ToArray();
        
        /// <summary>
        /// Gets the literal frame.
        /// </summary>
        public object[] GetLiterals() => literals.ToArray();
        
        /// <summary>
        /// Gets the current instruction pointer.
        /// </summary>
        public int CurrentIP => bytecodes.Count;
        
        /// <summary>
        /// Calculates the maximum stack depth required by the bytecode.
        /// </summary>
        public int CalculateMaxStackDepth()
        {
            return CalculateMaxStackDepth(bytecodes.ToArray());
        }
        
        /// <summary>
        /// Calculates the maximum stack depth required by the given bytecode array.
        /// </summary>
        public static int CalculateMaxStackDepth(byte[] bytes)
        {
            int currentDepth = 0;
            int maxDepth = 0;
            int pc = 0;
            
            while (pc < bytes.Length)
            {
                byte bytecode = bytes[pc];
                
                // Analyze stack effect of each bytecode according to Blue Book
                if (bytecode <= 15) // Push Receiver Variable
                {
                    currentDepth++;
                    pc++;
                }
                else if (bytecode <= 31) // Push Temporary Location
                {
                    currentDepth++;
                    pc++;
                }
                else if (bytecode <= 63) // Push Literal Constant
                {
                    currentDepth++;
                    pc++;
                }
                else if (bytecode <= 95) // Push Literal Variable
                {
                    currentDepth++;
                    pc++;
                }
                else if (bytecode <= 103) // Pop and Store Receiver Variable
                {
                    currentDepth--; // Pop value
                    pc++;
                }
                else if (bytecode <= 111) // Pop and Store Temporary Location
                {
                    currentDepth--; // Pop value
                    pc++;
                }
                else if (bytecode <= 119) // Push special constants
                {
                    currentDepth++;
                    pc++;
                }
                else if (bytecode <= 125) // Returns
                {
                    // Returns don't affect max calculation
                    pc++;
                }
                else if (bytecode == 128) // Extended Push
                {
                    currentDepth++;
                    pc += 3; // Skip 2 extension bytes
                }
                else if (bytecode == 129) // Extended Store (non-popping)
                {
                    // Store doesn't change stack
                    pc += 3;
                }
                else if (bytecode == 130) // Extended Pop and Store
                {
                    currentDepth--;
                    pc += 3;
                }
                else if (bytecode == 131) // Send Literal Selector
                {
                    pc++;
                    if (pc < bytes.Length)
                    {
                        int argCount = (bytes[pc] >> 5) & 0x07;
                        currentDepth -= (argCount + 1); // Pop receiver + args
                        currentDepth++; // Push result
                        pc++;
                    }
                }
                else if (bytecode == 132) // Double Extended Send
                {
                    pc++;
                    if (pc < bytes.Length)
                    {
                        int argCount = bytes[pc];
                        currentDepth -= (argCount + 1); // Pop receiver + args
                        currentDepth++; // Push result
                        pc += 2; // Skip selector byte
                    }
                }
                else if (bytecode == 135) // Pop Stack Top
                {
                    currentDepth--;
                    pc++;
                }
                else if (bytecode == 136) // Duplicate Stack Top
                {
                    currentDepth++;
                    pc++;
                }
                else if (bytecode == 137) // Push Active Context
                {
                    currentDepth++;
                    pc++;
                }
                else if (bytecode >= 144 && bytecode <= 151) // Jump
                {
                    pc += 2; // Jump has 1 extension byte
                }
                else if (bytecode >= 152 && bytecode <= 159) // Pop and Jump On False
                {
                    currentDepth--; // Pop condition
                    pc += 2;
                }
                else if (bytecode >= 160 && bytecode <= 167) // Long Jump
                {
                    pc += 2;
                }
                else if (bytecode >= 168 && bytecode <= 175) // Pop and Long Jump
                {
                    currentDepth--; // Pop condition
                    pc += 2;
                }
                else if (bytecode >= 176 && bytecode <= 191) // Send Arithmetic Message
                {
                    // Arithmetic messages typically have 1 arg
                    currentDepth -= 2; // Pop receiver + arg
                    currentDepth++; // Push result
                    pc++;
                }
                else if (bytecode >= 192 && bytecode <= 207) // Send Special Message
                {
                    // Special messages vary - conservatively assume 1 arg
                    currentDepth -= 2; // Pop receiver + arg
                    currentDepth++; // Push result
                    pc++;
                }
                else if (bytecode >= 208 && bytecode <= 223) // Send Literal Selector With No Arguments
                {
                    currentDepth--; // Pop receiver
                    currentDepth++; // Push result
                    pc++;
                }
                else if (bytecode >= 224 && bytecode <= 239) // Send Literal Selector With 1 Argument
                {
                    currentDepth -= 2; // Pop receiver + 1 arg
                    currentDepth++; // Push result
                    pc++;
                }
                else if (bytecode >= 240 && bytecode <= 255) // Send Literal Selector With 2 Arguments
                {
                    currentDepth -= 3; // Pop receiver + 2 args
                    currentDepth++; // Push result
                    pc++;
                }
                else
                {
                    // Unknown bytecode
                    pc++;
                }
                
                // Track maximum depth
                if (currentDepth > maxDepth)
                {
                    maxDepth = currentDepth;
                }
                
                // Sanity check - stack shouldn't go negative  
                if (currentDepth < 0)
                {
                    currentDepth = 0;
                }
            }
            
            // Return exact max depth without buffer
            return maxDepth;
        }
        
        /// <summary>
        /// Adds a literal to the frame and returns its index.
        /// </summary>
        public int AddLiteral(object literal)
        {
            // Check for existing literal by value equality
            foreach (var kvp in literalIndex)
            {
                if (LiteralsEqual(kvp.Key, literal))
                    return kvp.Value;
            }
            
            var index = literals.Count;
            literals.Add(literal);
            literalIndex[literal] = index;
            return index;
        }
        
        private bool LiteralsEqual(object a, object b)
        {
            if (a == null || b == null) return a == b;
            if (a is Symbol symA && b is Symbol symB) return symA.Value == symB.Value;
            if (a is Association assocA && b is Association assocB) return assocA.Key.Value == assocB.Key.Value;
            if (a is string strA && b is string strB) return strA == strB;
            if (a is int intA && b is int intB) return intA == intB;
            if (a is bool boolA && b is bool boolB) return boolA == boolB;
            if (a is NilObject && b is NilObject) return true;
            return a.Equals(b);
        }
        
        /// <summary>
        /// Emits a single bytecode.
        /// </summary>
        public void Emit(byte bytecode)
        {
            bytecodes.Add(bytecode);
        }
        
        /// <summary>
        /// Emits multiple bytecodes.
        /// </summary>
        public void EmitBytes(params byte[] bytes)
        {
            bytecodes.AddRange(bytes);
        }
        
        /// <summary>
        /// Patches a bytecode at the given position.
        /// </summary>
        public void PatchByte(int position, byte value)
        {
            if (position < bytecodes.Count)
                bytecodes[position] = value;
        }
        
        // Push operations
        
        public void PushReceiverVariable(int index)
        {
            if (index <= 15)
            {
                Emit((byte)(0 + index)); // 0-15
            }
            else
            {
                Emit(128); // Extended push
                Emit(0);   // Receiver variable
                Emit((byte)index);
            }
        }
        
        public void PushTemporary(int index)
        {
            if (index <= 15)
            {
                Emit((byte)(16 + index)); // 16-31
            }
            else
            {
                Emit(128); // Extended push
                Emit(16);  // Temporary variable
                Emit((byte)index);
            }
        }
        
        public void PushLiteralConstant(object literal)
        {
            var index = AddLiteral(literal);
            if (index <= 31)
            {
                // Bytecodes 32-63: Push Literal Constant #0 to #31
                Emit((byte)(32 + index));
            }
            else
            {
                // Use extended push for indices > 31
                Emit(128); // Extended push
                Emit(32);  // Push literal constant (type = 2)
                Emit((byte)index);
            }
        }
        
        public void PushLiteral(object literal)
        {
            // Backward compatibility - redirects to new method
            PushLiteralConstant(literal);
        }
        
        public void PushLiteralVariable(string name)
        {
            // For literal variables, we need an Association in the literals
            // The Association's value slot contains the actual variable value
            var index = AddLiteral(new Association(name, null));
            if (index <= 31)
            {
                // Bytecodes 64-95: Push Literal Variable #0 to #31
                Emit((byte)(64 + index));
            }
            else
            {
                // Use extended push for indices > 31
                Emit(128); // Extended push
                Emit(64);  // Push literal variable (type = 4)
                Emit((byte)index);
            }
        }
        
        public void PushSelf()
        {
            Emit(112); // Push receiver
        }
        
        public void PushNil()
        {
            Emit(115); // Push nil
        }
        
        public void PushTrue()
        {
            Emit(113); // Push true
        }
        
        public void PushFalse()
        {
            Emit(114); // Push false
        }
        
        public void PushMinusOne()
        {
            Emit(116); // Push -1
        }
        
        public void PushZero()
        {
            Emit(117); // Push 0
        }
        
        public void PushOne()
        {
            Emit(118); // Push 1
        }
        
        public void PushTwo()
        {
            Emit(119); // Push 2
        }
        
        // Store operations
        
        public void StoreReceiverVariable(int index)
        {
            if (index <= 7)
            {
                // Store and pop: 96-103
                Emit((byte)(96 + index));
            }
            else
            {
                Emit(129); // Extended store
                Emit(96);  // Store receiver variable
                Emit((byte)index);
                Pop();     // Explicit pop
            }
        }
        
        public void StoreTemporary(int index)
        {
            if (index <= 7)
            {
                // Store and pop: 104-111
                Emit((byte)(104 + index));
            }
            else
            {
                Emit(129); // Extended store
                Emit(104); // Store temporary
                Emit((byte)index);
                Pop();     // Explicit pop
            }
        }
        
        public void StoreLiteralVariable(string name)
        {
            var index = AddLiteral(new Association(name, null));
            Emit(129); // Extended store
            Emit(96);  // Store literal variable
            Emit((byte)index);
            Pop();     // Explicit pop
        }
        
        // Stack operations
        
        public void Pop()
        {
            Emit(135); // Pop stack
        }
        
        public void Dup()
        {
            Emit(136); // Duplicate top
        }
        
        // Return operations
        
        public void ReturnSelf()
        {
            Emit(120); // Return self
        }
        
        public void ReturnTop()
        {
            Emit(124); // Return top from method
        }
        
        public void ReturnTopFromBlock()
        {
            Emit(125); // Return top from block
        }
        
        // Jump operations
        
        public int EmitJumpPlaceholder()
        {
            var position = CurrentIP;
            EmitBytes(0, 0); // Placeholder for jump
            return position;
        }
        
        public void PatchJump(int position, int offset)
        {
            if (offset <= 8)
            {
                // Short jump: 144-151
                bytecodes[position] = (byte)(143 + offset);
                bytecodes.RemoveAt(position + 1); // Remove extra byte
            }
            else
            {
                // Long jump: 160-167
                var highBits = (offset - 1) >> 8;
                var lowBits = (offset - 1) & 0xFF;
                bytecodes[position] = (byte)(160 + (highBits & 0x07));
                bytecodes[position + 1] = (byte)lowBits;
            }
        }
        
        public int EmitConditionalJumpPlaceholder(bool jumpOnTrue)
        {
            var position = CurrentIP;
            EmitBytes(0, 0); // Placeholder
            return position;
        }
        
        public void PatchConditionalJump(int position, int offset, bool jumpOnTrue)
        {
            if (offset <= 8)
            {
                // Short conditional jump: 152-159 (false)
                if (!jumpOnTrue)
                {
                    bytecodes[position] = (byte)(151 + offset);
                    bytecodes.RemoveAt(position + 1);
                }
                else
                {
                    // No short jump on true in Blue Book
                    var highBits = (offset - 1) >> 8;
                    var lowBits = (offset - 1) & 0xFF;
                    bytecodes[position] = (byte)(168 + (highBits & 0x03));
                    bytecodes[position + 1] = (byte)lowBits;
                }
            }
            else
            {
                // Long conditional jump
                var highBits = (offset - 1) >> 8;
                var lowBits = (offset - 1) & 0xFF;
                if (jumpOnTrue)
                {
                    // 168-171: pop and jump on true
                    bytecodes[position] = (byte)(168 + (highBits & 0x03));
                }
                else
                {
                    // 172-175: pop and jump on false
                    bytecodes[position] = (byte)(172 + (highBits & 0x03));
                }
                bytecodes[position + 1] = (byte)lowBits;
            }
        }
        
        // Block operations
        
        public int EmitBlockCopy(int argCount)
        {
            // This is simplified - real implementation needs proper block bytecode
            // For now, emit placeholder that will be patched
            var position = CurrentIP;
            Emit(137); // Push active context (placeholder for block)
            EmitBytes(0, 0); // Placeholder for block size
            return position;
        }
        
        public void PatchBlockSize(int blockCopyPosition, int blockSize)
        {
            // Patch the block size in the BlockCopy instruction
            bytecodes[blockCopyPosition + 1] = (byte)(blockSize >> 8);
            bytecodes[blockCopyPosition + 2] = (byte)(blockSize & 0xFF);
        }
        
        // Send operations - Following Blue Book specification
        
        /// <summary>
        /// Special selectors from Blue Book.
        /// Arithmetic (176-191), Special (192-207), and others embedded in 208-255.
        /// </summary>
        internal static readonly Dictionary<string, (int bytecode, int args)> SpecialSelectors = new()
        {
            // Arithmetic selectors (176-191) - all binary (1 arg)
            ["+"] = (176, 1),
            ["-"] = (177, 1),
            ["<"] = (178, 1),
            [">"] = (179, 1),
            ["<="] = (180, 1),
            [">="] = (181, 1),
            ["="] = (182, 1),
            ["~="] = (183, 1),
            ["*"] = (184, 1),
            ["/"] = (185, 1),
            ["\\\\"] = (186, 1),  // mod
            ["@"] = (187, 1),
            ["bitShift:"] = (188, 1),
            ["//"] = (189, 1),      // div
            ["bitAnd:"] = (190, 1),
            ["bitOr:"] = (191, 1),
            
            // Special message selectors (192-207)
            ["at:"] = (192, 1),
            ["at:put:"] = (193, 2),
            ["size"] = (194, 0),
            ["next"] = (195, 0),
            ["nextPut:"] = (196, 1),
            ["atEnd"] = (197, 0),
            ["=="] = (198, 1),
            ["class"] = (199, 0),
            ["blockCopy:"] = (200, 1),
            ["value"] = (201, 0),
            ["value:"] = (202, 1),
            ["do:"] = (203, 1),
            ["new"] = (204, 0),
            ["new:"] = (205, 1),
            ["x"] = (206, 0),
            ["y"] = (207, 0)
        };
        
        /// <summary>
        /// Emits a send bytecode according to Blue Book specification.
        /// Bytecodes 176-191: Arithmetic messages
        /// Bytecodes 192-207: Special messages
        /// Bytecodes 208-223: Send Literal Selector With No Arguments
        /// Bytecodes 224-239: Send Literal Selector With 1 Argument
        /// Bytecodes 240-255: Send Literal Selector With 2 Arguments
        /// </summary>
        public void EmitSend(string selector, int argCount)
        {
            // Check if this is a special selector
            if (SpecialSelectors.TryGetValue(selector, out var special))
            {
                // Use the special bytecode directly
                Emit((byte)special.bytecode);
                return;
            }
            
            // Regular send: add selector to literal frame
            var selectorIndex = AddLiteral(new Symbol(selector));
            
            // Check for optimized bytecode ranges for 0, 1, 2 arguments
            if (argCount == 0 && selectorIndex <= 15)
            {
                // Bytecodes 208-223: Send Literal Selector With No Arguments
                Emit((byte)(208 + selectorIndex));
            }
            else if (argCount == 1 && selectorIndex <= 15)
            {
                // Bytecodes 224-239: Send Literal Selector With 1 Argument
                Emit((byte)(224 + selectorIndex));
            }
            else if (argCount == 2 && selectorIndex <= 15)
            {
                // Bytecodes 240-255: Send Literal Selector With 2 Arguments
                Emit((byte)(240 + selectorIndex));
            }
            else if (argCount <= 7 && selectorIndex <= 31)
            {
                // Bytecode 128-191: Send #kkkk With jjj Arguments
                // Binary: 1jjjkkkk where jjj = arg count, kkkk = selector index
                var bytecode = 128 | (argCount << 5) | selectorIndex;
                Emit((byte)bytecode);
            }
            else if (argCount <= 7 && selectorIndex <= 63)
            {
                // Use single extended send (131)
                Emit(131); // Single extended send
                Emit((byte)((argCount << 5) | (selectorIndex & 0x1F)));
            }
            else
            {
                // Use double extended send (132) for large selector indices or arg counts
                Emit(132); // Double extended send
                Emit((byte)argCount);
                Emit((byte)selectorIndex);
            }
        }
        
        /// <summary>
        /// Backward compatibility wrapper - redirects to EmitSend.
        /// </summary>
        public void SendMessage(string selector, int argCount)
        {
            EmitSend(selector, argCount);
        }
        
        /// <summary>
        /// Emits a super send bytecode according to Blue Book specification.
        /// Uses extended bytecodes 133 (single) and 134 (double).
        /// </summary>
        public void EmitSuperSend(string selector, int argCount)
        {
            var index = AddLiteral(new Symbol(selector));
            
            if (argCount <= 7 && index <= 31)
            {
                Emit(133); // Single extended super send
                Emit((byte)((argCount << 5) | index));
            }
            else
            {
                Emit(134); // Double extended super send
                Emit((byte)argCount);
                Emit((byte)index);
            }
        }
        
        /// <summary>
        /// Backward compatibility wrapper.
        /// </summary>
        public void SendSuperMessage(string selector, int argCount)
        {
            EmitSuperSend(selector, argCount);
        }
    }
    
    /// <summary>
    /// Complete bytecode compiler for Smalltalk methods following Blue Book specification.
    /// </summary>
    public class BytecodeCompiler
    {
        private CompilationEnvironment environment = null!;
        private BytecodeEmitter emitter = null!;
        private string selector = "";
        private int primitiveNumber = 0;
        private bool hasPrimitive = false;
        private int nextCascadeTemp = 0;
        private int scratchTempIndex = -1;
        
        /// <summary>
        /// Compiles a file-scope expression to bytecode.
        /// The expression will be compiled as if it were a method with no arguments.
        /// </summary>
        public CompiledMethodData CompileExpressionFromTree(
            Smalltalk80Parser.ExpressionContext expression)
        {
            // Initialize compilation state
            environment = new CompilationEnvironment();
            emitter = new BytecodeEmitter();
            selector = "doIt"; // Standard selector for expressions
            primitiveNumber = 0;
            hasPrimitive = false;
            nextCascadeTemp = 0;
            scratchTempIndex = -1;
            
            try
            {
                // No arguments or temporaries for file-scope expressions
                environment.ArgumentCount = 0;
                environment.TemporaryCount = 0;
                
                // First pass: collect literals
                var visitor = new LiteralCollector(emitter, environment);
                visitor.Visit(expression);
                
                // Second pass: compile the expression
                CompileExpression(expression);
                
                // Expression should leave its result on the stack
                // Add return if not already present
                if (emitter.GetBytecodes().Length == 0 || 
                    emitter.GetBytecodes()[^1] != 124) // returnTop
                {
                    emitter.ReturnTop();
                }
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Error compiling expression: {ex.Message}");
                // Return minimal stub
                emitter = new BytecodeEmitter();
                emitter.PushNil();
                emitter.ReturnTop();
            }
            
            return new CompiledMethodData
            {
                Selector = selector,
                ArgumentCount = 0,
                TemporaryCount = environment.TemporaryCount,
                IsPrimitive = false,
                PrimitiveNumber = 0,
                Bytecode = emitter.GetBytecodes(),
                Literals = emitter.GetLiterals()
            };
        }
        
        /// <summary>
        /// Compiles a Smalltalk method from a parse tree to Blue Book bytecode.
        /// </summary>
        public CompiledMethodData CompileMethodFromTree(
            Smalltalk80Parser.MethodDefContext methodDef,
            List<string> instanceVars,
            Dictionary<string, object>? classVars = null,
            Dictionary<string, object>? poolVars = null)
        {
            // Initialize compilation state
            environment = new CompilationEnvironment();
            emitter = new BytecodeEmitter();
            selector = "";
            primitiveNumber = 0;
            hasPrimitive = false;
            nextCascadeTemp = 0;
            scratchTempIndex = -1;
            
            // Set up instance variables with correct offsets
            for (int i = 0; i < instanceVars.Count; i++)
            {
                environment.InstanceVariables[instanceVars[i]] = i;
            }
            
            // Set up class variables
            if (classVars != null)
            {
                foreach (var kvp in classVars)
                {
                    environment.ClassVariables[kvp.Key] = kvp.Value;
                }
            }
            
            // Set up pool variables
            if (poolVars != null)
            {
                foreach (var kvp in poolVars)
                {
                    environment.PoolVariables[kvp.Key] = kvp.Value;
                }
            }
            
            try
            {
                // Process method header
                ProcessMethodHeader(methodDef.methodHeader());
                
                // Process temporaries
                if (methodDef.temporaries() != null)
                {
                    ProcessTemporaries(methodDef.temporaries());
                }
                
                // Process primitive declaration
                if (methodDef.primitiveDecl() != null)
                {
                    ProcessPrimitive(methodDef.primitiveDecl());
                }
                
                // First pass: collect literals
                CollectLiterals(methodDef.methodBody());
                
                // Second pass: generate bytecode
                CompileMethodBody(methodDef.methodBody());
                
                // Ensure method has a return
                EnsureMethodReturn();
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Error compiling method: {ex.Message}");
                // Return minimal stub method
                emitter = new BytecodeEmitter();
                emitter.ReturnSelf();
            }
            
            return new CompiledMethodData
            {
                Selector = selector,
                ArgumentCount = environment.ArgumentCount,
                TemporaryCount = environment.TemporaryCount,
                IsPrimitive = hasPrimitive,
                PrimitiveNumber = primitiveNumber,
                Bytecode = emitter.GetBytecodes(),
                Literals = emitter.GetLiterals()
            };
        }
        
        /// <summary>
        /// Compiles a Smalltalk method from source text to Blue Book bytecode.
        /// (Kept for backwards compatibility)
        /// </summary>
        public CompiledMethodData CompileMethod(
            string methodSource,
            List<string> instanceVars,
            Dictionary<string, object>? classVars = null,
            Dictionary<string, object>? poolVars = null)
        {
            // Initialize compilation state
            environment = new CompilationEnvironment();
            emitter = new BytecodeEmitter();
            selector = "";
            primitiveNumber = 0;
            hasPrimitive = false;
            nextCascadeTemp = 0;
            scratchTempIndex = -1;
            
            // Set up instance variables with correct offsets
            // IMPORTANT: The instanceVars list must contain ALL instance variables,
            // including inherited ones, in the correct order (superclass vars first).
            // The caller (SimpleCompiler) is responsible for computing the full list.
            for (int i = 0; i < instanceVars.Count; i++)
            {
                environment.InstanceVariables[instanceVars[i]] = i;
            }
            
            // Set up class variables
            if (classVars != null)
            {
                foreach (var kvp in classVars)
                {
                    environment.ClassVariables[kvp.Key] = kvp.Value;
                }
            }
            
            // Set up pool variables
            if (poolVars != null)
            {
                foreach (var kvp in poolVars)
                {
                    environment.PoolVariables[kvp.Key] = kvp.Value;
                }
            }
            
            try
            {
                // Parse the method
                var inputStream = new Antlr4.Runtime.AntlrInputStream(methodSource);
                var lexer = new Smalltalk80Lexer(inputStream);
                var tokenStream = new Antlr4.Runtime.CommonTokenStream(lexer);
                var parser = new Smalltalk80Parser(tokenStream);
                parser.RemoveErrorListeners();
                
                var methodDef = parser.methodDef();
                
                // Process method header
                ProcessMethodHeader(methodDef.methodHeader());
                
                // Process temporaries
                if (methodDef.temporaries() != null)
                {
                    ProcessTemporaries(methodDef.temporaries());
                }
                
                // Process primitive declaration
                if (methodDef.primitiveDecl() != null)
                {
                    ProcessPrimitive(methodDef.primitiveDecl());
                }
                
                // First pass: collect literals
                CollectLiterals(methodDef.methodBody());
                
                // Second pass: generate bytecode
                CompileMethodBody(methodDef.methodBody());
                
                // Ensure method has a return
                EnsureMethodReturn();
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Error compiling method: {ex.Message}");
                // Return minimal stub method
                emitter = new BytecodeEmitter();
                emitter.ReturnSelf();
            }
            
            return new CompiledMethodData
            {
                Selector = selector,
                ArgumentCount = environment.ArgumentCount,
                TemporaryCount = environment.TemporaryCount,
                IsPrimitive = hasPrimitive,
                PrimitiveNumber = primitiveNumber,
                Literals = emitter.GetLiterals(),
                Bytecode = emitter.GetBytecodes()
            };
        }
        
        private void ProcessMethodHeader(Smalltalk80Parser.MethodHeaderContext header)
        {
            if (header.unarySelector() != null)
            {
                selector = header.unarySelector().GetText();
                environment.ArgumentCount = 0;
            }
            else if (header.binarySelector() != null)
            {
                selector = header.binarySelector().GetText();
                var arg = header.formalArg(0);
                if (arg != null)
                {
                    environment.Arguments[arg.GetText()] = 0;
                    environment.ArgumentCount = 1;
                }
            }
            else
            {
                // Keyword selector
                var keywords = header.identifierColon();
                var parts = new List<string>();
                var args = header.formalArg();
                
                for (int i = 0; i < keywords.Length; i++)
                {
                    var keywordText = keywords[i].GetText();
                    parts.Add(keywordText);
                    if (i < args.Length)
                    {
                        var argText = args[i].GetText();
                        environment.Arguments[argText] = i;
                    }
                }
                
                selector = string.Join("", parts);
                environment.ArgumentCount = args.Length;
            }
        }
        
        private void ProcessTemporaries(Smalltalk80Parser.TemporariesContext temps)
        {
            var tempNames = temps.temporaryName();
            for (int i = 0; i < tempNames.Length; i++)
            {
                var name = tempNames[i].GetText();
                environment.Temporaries[name] = environment.ArgumentCount + i;
            }
            environment.TemporaryCount = tempNames.Length;
        }
        
        private void ProcessPrimitive(Smalltalk80Parser.PrimitiveDeclContext primitive)
        {
            var text = primitive.GetText();
            var match = System.Text.RegularExpressions.Regex.Match(text, @"<primitive:\s*(\d+)>");
            if (match.Success && int.TryParse(match.Groups[1].Value, out var num))
            {
                hasPrimitive = true;
                primitiveNumber = num;
            }
        }
        
        private void CollectLiterals(Smalltalk80Parser.MethodBodyContext? body)
        {
            if (body == null) return;
            
            // Walk the tree to collect all literals that will be needed
            var visitor = new LiteralCollector(emitter, environment);
            visitor.Visit(body);
        }
        
        private void CompileMethodBody(Smalltalk80Parser.MethodBodyContext? body)
        {
            if (body == null)
            {
                emitter.PushSelf();
                return;
            }
            
            var returnStmt = body.returnStatement();
            if (returnStmt != null)
            {
                CompileReturnStatement(returnStmt);
                return;
            }
            
            var statements = body.statements();
            if (statements != null)
            {
                CompileStatements(statements);
            }
            else
            {
                emitter.PushSelf();
            }
        }
        
        private void CompileStatements(Smalltalk80Parser.StatementsContext stmts)
        {
            var statements = stmts.statement();
            
            for (int i = 0; i < statements.Length; i++)
            {
                bool isLast = (i == statements.Length - 1);
                CompileStatement(statements[i], isLast);
            }
        }
        
        private void CompileStatement(Smalltalk80Parser.StatementContext stmt, bool isLast)
        {
            var returnStmt = stmt.returnStatement();
            if (returnStmt != null)
            {
                CompileReturnStatement(returnStmt);
                return;
            }
            
            var exprStmt = stmt.expressionStatement();
            if (exprStmt != null)
            {
                CompileExpression(exprStmt.expression());
                
                // Pop intermediate results except for last statement
                if (!isLast)
                {
                    SpillResult();
                }
            }
        }
        
        private void CompileReturnStatement(Smalltalk80Parser.ReturnStatementContext returnStmt)
        {
            var expr = returnStmt.expression();
            if (expr != null)
            {
                CompileExpression(expr);
            }
            else
            {
                emitter.PushSelf();
            }
            
            if (environment.ScopeDepth > 0)
            {
                emitter.ReturnTopFromBlock();
            }
            else
            {
                emitter.ReturnTop();
            }
        }
        
        private void CompileExpression(Smalltalk80Parser.ExpressionContext expr)
        {
            var assignExpr = expr.assignmentExpr();
            if (assignExpr != null)
            {
                CompileAssignmentExpr(assignExpr);
            }
        }
        
        private void CompileAssignmentExpr(Smalltalk80Parser.AssignmentExprContext expr)
        {
            var variable = expr.variable();
            if (variable != null && expr.ASSIGN() != null)
            {
                // Assignment: compile RHS first
                CompileAssignmentExpr(expr.assignmentExpr());
                
                // Store leaves value on stack
                StoreVariable(variable.GetText(), leaveOnStack: true);
            }
            else
            {
                // No assignment, compile cascade expression
                var cascadeExpr = expr.cascadeExpr();
                if (cascadeExpr != null)
                {
                    CompileCascadeExpr(cascadeExpr);
                }
            }
        }
        
        private void CompileCascadeExpr(Smalltalk80Parser.CascadeExprContext expr)
        {
            var messageExpr = expr.messageExpr();
            var messageParts = expr.messagePart();
            
            if (messageParts != null && messageParts.Length > 0)
            {
                // Cascade: need to cache receiver
                var cascadeTemp = environment.AllocateHiddenTemp($"cascade{nextCascadeTemp++}");
                
                // Compile the base message expression
                CompileMessageExpr(messageExpr, cacheReceiver: cascadeTemp);
                
                // Process cascaded messages
                for (int i = 0; i < messageParts.Length; i++)
                {
                    bool isLast = (i == messageParts.Length - 1);
                    
                    // Pop previous result unless it's the first (already handled)
                    if (i > 0 || messageExpr != null)
                    {
                        SpillResult();
                    }
                    
                    // Push cached receiver
                    emitter.PushTemporary(cascadeTemp);
                    
                    // Compile the message part
                    CompileMessagePart(messageParts[i]);
                }
            }
            else
            {
                // No cascade, just compile the message
                CompileMessageExpr(messageExpr, cacheReceiver: -1);
            }
        }
        
        private void CompileMessageExpr(Smalltalk80Parser.MessageExprContext expr, int cacheReceiver = -1)
        {
            // Compile receiver and check if it's super
            var messageBase = expr.messageBase();
            bool receiverIsSuper = IsReceiverSuper(messageBase);
            CompileMessageBase(messageBase);
            
            // Cache receiver if needed (for cascades)
            if (cacheReceiver >= 0)
            {
                emitter.Dup();
                emitter.StoreTemporary(cacheReceiver);
            }
            
            // Process unary messages
            var unaryMessages = expr.unaryMessage();
            if (unaryMessages != null)
            {
                foreach (var msg in unaryMessages)
                {
                    var selector = msg.unarySelector().GetText();
                    if (receiverIsSuper)
                    {
                        emitter.EmitSuperSend(selector, 0);
                        receiverIsSuper = false; // Only the first message is a super send
                    }
                    else
                    {
                        emitter.EmitSend(selector, 0);
                    }
                }
            }
            
            // Process binary messages
            var binaryMessages = expr.binaryMessage();
            if (binaryMessages != null)
            {
                foreach (var msg in binaryMessages)
                {
                    var selector = msg.binarySelector().GetText();
                    CompileMessageBase(msg.messageBase());
                    if (receiverIsSuper)
                    {
                        emitter.EmitSuperSend(selector, 1);
                        receiverIsSuper = false; // Only the first message is a super send
                    }
                    else
                    {
                        emitter.EmitSend(selector, 1);
                    }
                }
            }
            
            // Process keyword message
            var keywordMessage = expr.keywordMessage();
            if (keywordMessage != null)
            {
                CompileKeywordMessage(keywordMessage, receiverIsSuper);
            }
        }
        
        private void CompileMessagePart(Smalltalk80Parser.MessagePartContext part)
        {
            var unaryMessage = part.unaryMessage();
            if (unaryMessage != null)
            {
                var selector = unaryMessage.unarySelector().GetText();
                emitter.SendMessage(selector, 0);
                return;
            }
            
            var binaryMessage = part.binaryMessage();
            if (binaryMessage != null)
            {
                var selector = binaryMessage.binarySelector().GetText();
                CompileMessageBase(binaryMessage.messageBase());
                emitter.SendMessage(selector, 1);
                return;
            }
            
            var keywordMessage = part.keywordMessage();
            if (keywordMessage != null)
            {
                CompileKeywordMessage(keywordMessage);
            }
        }
        
        private void CompileKeywordMessage(Smalltalk80Parser.KeywordMessageContext msg, bool isSuper = false)
        {
            var keywordParts = msg.keywordPart();
            var keywords = new List<string>();
            
            // Compile arguments
            foreach (var part in keywordParts)
            {
                keywords.Add(part.IDENTIFIER().GetText() + ":");
                CompileNonKeywordExpr(part.nonKeywordExpr());
            }
            
            // Build selector
            var selector = string.Join("", keywords);
            if (isSuper)
            {
                emitter.EmitSuperSend(selector, keywordParts.Length);
            }
            else
            {
                emitter.EmitSend(selector, keywordParts.Length);
            }
        }
        
        private void CompileNonKeywordExpr(Smalltalk80Parser.NonKeywordExprContext expr)
        {
            var messageBase = expr.messageBase();
            bool receiverIsSuper = IsReceiverSuper(messageBase);
            CompileMessageBase(messageBase);
            
            // Process unary messages
            var unaryMessages = expr.unaryMessage();
            if (unaryMessages != null)
            {
                foreach (var msg in unaryMessages)
                {
                    var selector = msg.unarySelector().GetText();
                    if (receiverIsSuper)
                    {
                        emitter.EmitSuperSend(selector, 0);
                        receiverIsSuper = false; // Only the first message is a super send
                    }
                    else
                    {
                        emitter.EmitSend(selector, 0);
                    }
                }
            }
            
            // Process binary messages
            var binaryMessages = expr.binaryMessage();
            if (binaryMessages != null)
            {
                foreach (var msg in binaryMessages)
                {
                    var selector = msg.binarySelector().GetText();
                    CompileMessageBase(msg.messageBase());
                    if (receiverIsSuper)
                    {
                        emitter.EmitSuperSend(selector, 1);
                        receiverIsSuper = false; // Only the first message is a super send
                    }
                    else
                    {
                        emitter.EmitSend(selector, 1);
                    }
                }
            }
        }
        
        private void CompileMessageBase(Smalltalk80Parser.MessageBaseContext baseCtx)
        {
            if (baseCtx.literal() != null)
            {
                CompileLiteral(baseCtx.literal());
            }
            else if (baseCtx.variable() != null)
            {
                var varName = baseCtx.variable().GetText();
                PushVariable(varName);
            }
            else if (baseCtx.parenthesizedExpr() != null)
            {
                CompileExpression(baseCtx.parenthesizedExpr().expression());
            }
            else if (baseCtx.block() != null)
            {
                CompileBlock(baseCtx.block());
            }
        }
        
        private void CompileBlock(Smalltalk80Parser.BlockContext block)
        {
            // Save current environment state
            var savedScopeDepth = environment.ScopeDepth;
            environment.ScopeDepth++;
            
            // Block arguments not fully implemented
            int argCount = 0;
            // TODO: Parse block arguments when grammar supports it
            
            // Emit BlockCopy
            var blockCopyPos = emitter.EmitBlockCopy(argCount);
            var blockStartIP = emitter.CurrentIP;
            
            // Compile block body
            var statements = block.statements();
            if (statements != null)
            {
                CompileStatements(statements);
            }
            else
            {
                emitter.PushNil();
            }
            
            // Ensure block returns
            emitter.ReturnTopFromBlock();
            
            // Calculate and patch block size
            var blockSize = emitter.CurrentIP - blockStartIP;
            emitter.PatchBlockSize(blockCopyPos, blockSize);
            
            // Restore environment
            environment.ScopeDepth = savedScopeDepth;
        }
        
        private void CompileLiteral(Smalltalk80Parser.LiteralContext literal)
        {
            if (literal.numberLiteral() != null)
            {
                var text = literal.numberLiteral().GetText();
                if (int.TryParse(text, out int intVal))
                {
                    // Use special bytecodes for small integers
                    switch (intVal)
                    {
                        case -1:
                            emitter.PushMinusOne();
                            break;
                        case 0:
                            emitter.PushZero();
                            break;
                        case 1:
                            emitter.PushOne();
                            break;
                        case 2:
                            emitter.PushTwo();
                            break;
                        default:
                            emitter.PushLiteralConstant(intVal);
                            break;
                    }
                }
                else if (double.TryParse(text, out double floatVal))
                {
                    emitter.PushLiteralConstant(floatVal);
                }
            }
            // Note: negativeNumber handling removed - grammar may not support it
            // Negative numbers should be handled as unary minus message
            else if (literal.stringConst() != null)
            {
                var text = literal.stringConst().GetText();
                var str = text.Substring(1, text.Length - 2); // Remove quotes
                emitter.PushLiteralConstant(str);
            }
            else if (literal.symbolConst() != null)
            {
                var text = literal.symbolConst().GetText();
                var sym = new Symbol(text.Substring(1)); // Remove #
                emitter.PushLiteralConstant(sym);
            }
            else if (literal.characterLiteral() != null)
            {
                var text = literal.characterLiteral().GetText();
                var ch = text[1]; // Get character after $
                emitter.PushLiteralConstant(ch);
            }
            else if (literal.arrayLiteral() != null)
            {
                // Array literals need special handling
                var array = literal.arrayLiteral();
                // For now, push as a literal array object
                emitter.PushLiteralConstant(array.GetText());
            }
            else if (literal.byteArrayLiteral() != null)
            {
                // Byte array literals
                var byteArray = literal.byteArrayLiteral();
                emitter.PushLiteralConstant(byteArray.GetText());
            }
            else
            {
                var text = literal.GetText();
                if (text == "true")
                {
                    emitter.PushTrue();
                }
                else if (text == "false")
                {
                    emitter.PushFalse();
                }
                else if (text == "nil")
                {
                    emitter.PushNil();
                }
            }
        }
        
        private void PushVariable(string name)
        {
            // Special variables
            if (name == "self")
            {
                emitter.PushSelf();
                return;
            }
            if (name == "super")
            {
                emitter.PushSelf(); // Super uses self as receiver
                return;
            }
            if (name == "true")
            {
                emitter.PushTrue();
                return;
            }
            if (name == "false")
            {
                emitter.PushFalse();
                return;
            }
            if (name == "nil")
            {
                emitter.PushNil();
                return;
            }
            
            // Check if it's an argument FIRST (arguments use different bytecode than temporaries)
            if (environment.Arguments.TryGetValue(name, out var argIndex))
            {
                // Arguments use bytecodes 48-63 via PushArgument
                if (argIndex <= 15)
                {
                    emitter.Emit((byte)(48 + argIndex));
                }
                else
                {
                    // Extended push for arguments > 15
                    emitter.Emit(128); // Extended push
                    emitter.Emit((byte)((argIndex << 6) | 0x30)); // Type bits for argument
                }
                return;
            }
            
            // Check if it's a temporary
            if (environment.Temporaries.TryGetValue(name, out var tempIndex))
            {
                emitter.PushTemporary(tempIndex);
                return;
            }
            
            // Check hidden temporaries
            if (environment.HiddenTemporaries.TryGetValue(name, out var hiddenIndex))
            {
                emitter.PushTemporary(hiddenIndex);
                return;
            }
            
            // Check instance variables
            if (environment.InstanceVariables.TryGetValue(name, out var instIndex))
            {
                emitter.PushReceiverVariable(instIndex);
                return;
            }
            
            // Check class variables (Blue Book: these use PushLiteralVariable with Association)
            if (environment.ClassVariables.ContainsKey(name))
            {
                emitter.PushLiteralVariable(name);
                return;
            }
            
            // Check pool variables (Blue Book: these also use PushLiteralVariable with Association)
            if (environment.PoolVariables.ContainsKey(name))
            {
                emitter.PushLiteralVariable(name);
                return;
            }
            
            // Global variable (also uses PushLiteralVariable with Association)
            emitter.PushLiteralVariable(name);
        }
        
        private void StoreVariable(string name, bool leaveOnStack)
        {
            // Check local variables (arguments and temporaries)
            var index = environment.GetVariableIndex(name);
            if (index.HasValue)
            {
                if (leaveOnStack)
                {
                    emitter.Dup();
                }
                emitter.StoreTemporary(index.Value);
                return;
            }
            
            // Check instance variables
            if (environment.InstanceVariables.TryGetValue(name, out var instIndex))
            {
                if (leaveOnStack)
                {
                    emitter.Dup();
                }
                emitter.StoreReceiverVariable(instIndex);
                return;
            }
            
            // Check class variables (Blue Book: these use StoreLiteralVariable with Association)
            if (environment.ClassVariables.ContainsKey(name))
            {
                if (leaveOnStack)
                {
                    emitter.Dup();
                }
                emitter.StoreLiteralVariable(name);
                return;
            }
            
            // Check pool variables (Blue Book: these also use StoreLiteralVariable with Association)
            if (environment.PoolVariables.ContainsKey(name))
            {
                if (leaveOnStack)
                {
                    emitter.Dup();
                }
                emitter.StoreLiteralVariable(name);
                return;
            }
            
            // Global variable (also uses StoreLiteralVariable with Association)
            if (leaveOnStack)
            {
                emitter.Dup();
            }
            emitter.StoreLiteralVariable(name);
        }
        
        private void SpillResult()
        {
            // Allocate scratch temp if needed
            if (scratchTempIndex < 0)
            {
                scratchTempIndex = environment.AllocateHiddenTemp("scratch");
            }
            
            // Store and pop to discard result
            emitter.StoreTemporary(scratchTempIndex);
        }
        
        private void EnsureMethodReturn()
        {
            var bytecodes = emitter.GetBytecodes();
            if (bytecodes.Length == 0 || !IsReturnBytecode(bytecodes[^1]))
            {
                emitter.ReturnTop();
            }
        }
        
        private bool IsReturnBytecode(byte bytecode)
        {
            // Blue Book return bytecodes: 120-125
            return bytecode >= 120 && bytecode <= 125;
        }
        
        private bool IsReceiverSuper(Smalltalk80Parser.MessageBaseContext baseCtx)
        {
            // Check if the receiver is the special variable "super"
            if (baseCtx.variable() != null)
            {
                var varName = baseCtx.variable().GetText();
                return varName == "super";
            }
            return false;
        }
        
        /// <summary>
        /// Helper class to collect literals in first pass.
        /// </summary>
        private class LiteralCollector : Smalltalk80BaseVisitor<object?>
        {
            private readonly BytecodeEmitter emitter;
            private readonly CompilationEnvironment? environment;
            
            // Reference to the static SpecialSelectors dictionary
            private static readonly Dictionary<string, (int bytecode, int args)> SpecialSelectors = BytecodeEmitter.SpecialSelectors;
            
            public LiteralCollector(BytecodeEmitter emitter, CompilationEnvironment? environment = null)
            {
                this.emitter = emitter;
                this.environment = environment;
            }
            
            public override object? VisitUnaryMessage(Smalltalk80Parser.UnaryMessageContext context)
            {
                var selector = context.unarySelector().GetText();
                // Only add to literals if not a special selector
                if (!SpecialSelectors.ContainsKey(selector))
                {
                    emitter.AddLiteral(new Symbol(selector));
                }
                return base.VisitUnaryMessage(context);
            }
            
            public override object? VisitBinaryMessage(Smalltalk80Parser.BinaryMessageContext context)
            {
                var selector = context.binarySelector().GetText();
                // Only add to literals if not a special selector
                if (!SpecialSelectors.ContainsKey(selector))
                {
                    emitter.AddLiteral(new Symbol(selector));
                }
                return base.VisitBinaryMessage(context);
            }
            
            public override object? VisitKeywordMessage(Smalltalk80Parser.KeywordMessageContext context)
            {
                var parts = context.keywordPart();
                var keywords = new List<string>();
                foreach (var part in parts)
                {
                    keywords.Add(part.IDENTIFIER().GetText() + ":");
                }
                var selector = string.Join("", keywords);
                // Only add to literals if not a special selector
                if (!SpecialSelectors.ContainsKey(selector))
                {
                    emitter.AddLiteral(new Symbol(selector));
                }
                return base.VisitKeywordMessage(context);
            }
            
            public override object? VisitVariable(Smalltalk80Parser.VariableContext context)
            {
                var name = context.GetText();
                
                // Skip special variables
                if (name == "self" || name == "super" || name == "true" || 
                    name == "false" || name == "nil")
                {
                    return base.VisitVariable(context);
                }
                
                // Check if it needs an Association in the literal frame
                // (i.e., it's a class variable, pool variable, or global variable)
                bool needsAssociation = true;
                if (environment != null)
                {
                    // Check if it's a local variable (argument, temporary, or instance variable)
                    // These DON'T need Associations
                    if (environment.Arguments.ContainsKey(name) ||
                        environment.Temporaries.ContainsKey(name) ||
                        environment.HiddenTemporaries.ContainsKey(name) ||
                        environment.InstanceVariables.ContainsKey(name))
                    {
                        needsAssociation = false;
                    }
                }
                
                // If it's a class variable, pool variable, or global variable,
                // add an Association to the literals for use with PushLiteralVariable
                if (needsAssociation)
                {
                    emitter.AddLiteral(new Association(name, null));
                }
                
                return base.VisitVariable(context);
            }
            
            public override object? VisitLiteral(Smalltalk80Parser.LiteralContext context)
            {
                // Collect literal constants
                if (context.numberLiteral() != null)
                {
                    var text = context.numberLiteral().GetText();
                    if (int.TryParse(text, out int intVal))
                    {
                        // Only add to literals if not a special small integer
                        if (intVal != -1 && intVal != 0 && intVal != 1 && intVal != 2)
                        {
                            emitter.AddLiteral(intVal);
                        }
                    }
                    else if (double.TryParse(text, out double floatVal))
                    {
                        emitter.AddLiteral(floatVal);
                    }
                }
                else if (context.stringConst() != null)
                {
                    var text = context.stringConst().GetText();
                    var str = text.Substring(1, text.Length - 2);
                    emitter.AddLiteral(str);
                }
                else if (context.symbolConst() != null)
                {
                    var text = context.symbolConst().GetText();
                    var sym = new Symbol(text.Substring(1));
                    emitter.AddLiteral(sym);
                }
                
                return base.VisitLiteral(context);
            }
        }
    }
